//! The manifest (`manifest.json`) and the Premiere-side protocol (`PREMIERE.md`): everything a
//! person or a script needs to render the corpus in Premiere Pro and put the output where the
//! harness looks for it. Both are regenerated on every run.

use std::path::Path;

use serde::{Deserialize, Serialize};

use crate::Error;
use crate::corpus::{Compare, CorpusSettings, PremiereEffect, Tolerance};

pub const VERSION: u32 = 1;

#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct MediaEntry {
    pub path: String,
    pub bytes: u64,
    /// FNV-1a 64 of the file: a changed generator is noticed, nothing more.
    pub fingerprint: String,
}

/// `CaseDef::premiere_effects` for the script: an Effects panel name and property values.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct PremiereEffectEntry {
    pub name: String,
    pub params: serde_json::Map<String, serde_json::Value>,
}

impl From<&PremiereEffect> for PremiereEffectEntry {
    fn from(e: &PremiereEffect) -> Self {
        PremiereEffectEntry { name: e.name.into(), params: e.params.iter().map(|(k, v)| (k.to_string(), serde_json::Value::from(*v))).collect() }
    }
}

#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct CaseEntry {
    pub id: String,
    pub title: String,
    pub group: String,
    pub effect: String,
    pub compare: Compare,
    pub about: String,
    pub xml_complete: bool,
    pub premiere_steps: Vec<String>,
    /// The same steps for `premiere/render.py` (empty iff `xml_complete`).
    pub premiere_effects: Vec<PremiereEffectEntry>,
    /// Why the case is expected to fail for now, when it is.
    pub known_failure: Option<String>,
    pub fcp7_xml: String,
    pub otio: String,
    pub fcproj: String,
    /// What the interchange exporters could not carry.
    pub warnings: Vec<String>,
    /// Where our render of the case is.
    pub ours_dir: String,
    /// Where Premiere's render of the case goes.
    pub reference_dir: String,
    pub frames: i64,
    pub samples: i64,
    pub tolerance: Tolerance,
}

#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct Manifest {
    pub version: u32,
    pub generated_by: String,
    pub settings: CorpusSettings,
    pub media: Vec<MediaEntry>,
    pub cases: Vec<CaseEntry>,
    /// The directory the reference renders are read from (`plan/premiere/fidelity`, local only).
    pub reference_root: String,
}

/// FNV-1a 64-bit hash as 16 hex digits.
pub fn fnv64(bytes: &[u8]) -> String {
    let mut h: u64 = 0xcbf2_9ce4_8422_2325;
    for &b in bytes {
        h = (h ^ u64::from(b)).wrapping_mul(0x100_0000_01b3);
    }
    format!("{h:016x}")
}

pub fn media_entry(path: &Path) -> Result<MediaEntry, Error> {
    let bytes = std::fs::read(path).map_err(|e| Error::Io(path.to_path_buf(), e))?;
    Ok(MediaEntry { path: path.to_string_lossy().to_string(), bytes: bytes.len() as u64, fingerprint: fnv64(&bytes) })
}

/// The human protocol for the Premiere side.
pub fn premiere_md(m: &Manifest) -> String {
    let s = &m.settings;
    let fps = if s.frame_rate.den == 1 { s.frame_rate.num.to_string() } else { format!("{}/{}", s.frame_rate.num, s.frame_rate.den) };
    let mut out = String::new();
    out.push_str("# Rendering the fidelity corpus in Premiere Pro\n\n");
    out.push_str(&format!(
        "Generated by `cargo xtask fidelity` (manifest v{}). Every case below is a FilmCraft-authored sequence \
         ({}×{}, {fps} fps, {} Hz) on media FilmCraft generated itself; the paths are absolute for this machine. \
         Premiere's renders go under `{}` (gitignored: they never leave this machine), one directory per case, and \
         `cargo xtask fidelity` scores them on its next run.\n\n",
        m.version, s.width, s.height, s.sample_rate, m.reference_root
    ));
    out.push_str("## Once per case\n\n");
    out.push_str("1. **Import** the case's FCP7 XML (File ▸ Import). Premiere makes a bin with the sequence and the media; open the sequence.\n");
    out.push_str(&format!(
        "2. **Check the sequence settings** match the corpus ({}×{}, {fps} fps, {} Hz, square pixels). Fix them before anything else if not.\n",
        s.width, s.height, s.sample_rate
    ));
    out.push_str("3. **Do the case's manual steps**, if it lists any (effects FCP7 XML cannot carry). Cases marked *XML complete* need nothing.\n");
    out.push_str("4. **Export** (File ▸ Export ▸ Media), whole sequence, into the case's reference directory:\n");
    out.push_str("   - video cases: Format **PNG**, *Export As Sequence* on, Match Source size and frame rate, 8 bpc, *Include Alpha Channel* off, \
                  *Use Maximum Render Quality* off, *Render at Maximum Depth* off, Rec. 709 output; name the file `<case>.png` (Premiere numbers the frames);\n");
    out.push_str("   - audio cases: Format **Waveform Audio**, 48000 Hz, 24-bit, stereo (match the corpus); name it `<case>.wav`.\n");
    out.push_str(
        "   The harness also reads a ProRes / H.264 movie or TIFF / BMP stills if that is what you have; a WAV beside a movie wins over the movie's sound.\n",
    );
    out.push_str("5. Run `cargo xtask fidelity` again. The report lists every case with a render as *pass* or *fail* against its tolerance, and the rest as *no reference*.\n\n");
    out.push_str(
        "Keep the Premiere project (`.prproj`) you make in the same local directory; nothing under it is ever committed. \
                  Never commit, screenshot into the repo or embed anything Premiere produced ([AGENTS.md §1](../../AGENTS.md)).\n\n",
    );
    out.push_str("## By script\n\n");
    out.push_str(
        "With [premiere-cli](https://github.com/strangeparts/premiere-cli) installed and Premiere Pro open on this machine, \
         `python3 crates/fidelity/premiere/render.py <manifest.json>` does steps 1–4 for every case: import, settings check, \
         the effects below by their Effect Controls names, one PNG per frame through Premiere's frame export at the exact tick of \
         every frame, and the sound cases through Media Encoder given `--audio-preset <file>.epr` (a Waveform Audio 48 kHz 24-bit \
         preset saved once from Premiere's export dialog). Then step 5.\n\n",
    );
    out.push_str("## Media\n\n| File | Bytes | Fingerprint |\n|---|---|---|\n");
    for e in &m.media {
        out.push_str(&format!("| `{}` | {} | `{}` |\n", e.path, e.bytes, e.fingerprint));
    }
    out.push_str("\n## Cases\n\n");
    let mut group = "";
    for c in &m.cases {
        if c.group != group {
            group = &c.group;
            out.push_str(&format!("### {group}\n\n"));
        }
        let side = match c.compare {
            Compare::Video => "picture",
            Compare::Audio => "sound",
        };
        out.push_str(&format!("#### `{}`: {}\n\n", c.id, c.title));
        out.push_str(&format!("- Compares the {side}. {}\n", c.about));
        out.push_str(&format!("- Import: `{}` (also `{}` as OpenTimelineIO, `{}` as the FilmCraft project).\n", c.fcp7_xml, c.otio, c.fcproj));
        if c.xml_complete {
            out.push_str("- XML complete: import, export, done.\n");
        } else {
            out.push_str("- After the import:\n");
            for step in &c.premiere_steps {
                out.push_str(&format!("  1. {step}\n"));
            }
            for e in &c.premiere_effects {
                let params: Vec<String> = e.params.iter().map(|(k, v)| format!("{k} = {v}")).collect();
                out.push_str(&format!("- By script: **{}**{}{}\n", e.name, if params.is_empty() { "" } else { ": " }, params.join(", ")));
            }
        }
        let name = match c.compare {
            Compare::Video => format!("{}.png", c.id),
            Compare::Audio => format!("{}.wav", c.id),
        };
        out.push_str(&format!("- Export to: `{}/{name}`\n", c.reference_dir));
        if !c.warnings.is_empty() {
            out.push_str("- Exporter notes: ");
            out.push_str(&c.warnings.join("; "));
            out.push('\n');
        }
        out.push('\n');
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn fnv64_is_the_standard_hash() {
        assert_eq!(fnv64(b""), "cbf29ce484222325");
        assert_eq!(fnv64(b"a"), "af63dc4c8601ec8c");
    }

    #[test]
    fn premiere_md_lists_every_case_with_its_steps() {
        let m = Manifest {
            version: VERSION,
            generated_by: "test".into(),
            settings: CorpusSettings::default(),
            media: vec![MediaEntry { path: "/m/footage_a.mov".into(), bytes: 10, fingerprint: "00".into() }],
            cases: vec![
                CaseEntry {
                    id: "cut".into(),
                    title: "Hard cut".into(),
                    group: "Baseline".into(),
                    effect: String::new(),
                    compare: Compare::Video,
                    about: "the floor".into(),
                    xml_complete: true,
                    premiere_steps: vec![],
                    premiere_effects: vec![],
                    known_failure: None,
                    fcp7_xml: "/o/cases/cut/cut.xml".into(),
                    otio: "/o/cases/cut/cut.otio".into(),
                    fcproj: "/o/cases/cut/cut.fcproj".into(),
                    warnings: vec![],
                    ours_dir: "/o/ours/cut".into(),
                    reference_dir: "/plan/premiere/fidelity/cut".into(),
                    frames: 72,
                    samples: 144_000,
                    tolerance: Tolerance::BASELINE,
                },
                CaseEntry {
                    id: "gaussian_blur".into(),
                    title: "Gaussian Blur 20".into(),
                    group: "Effects".into(),
                    effect: "Gaussian Blur".into(),
                    compare: Compare::Audio,
                    about: "kernel".into(),
                    xml_complete: false,
                    premiere_steps: vec!["Apply it".into(), "Blurriness 20".into()],
                    premiere_effects: vec![PremiereEffectEntry {
                        name: "Gaussian Blur (Legacy)".into(),
                        params: [("Blurriness".to_string(), serde_json::json!(20.0)), ("Repeat Edge Pixels".to_string(), serde_json::json!(false))]
                            .into_iter()
                            .collect(),
                    }],
                    known_failure: Some("kernel differs".into()),
                    fcp7_xml: "x".into(),
                    otio: "y".into(),
                    fcproj: "z".into(),
                    warnings: vec!["point keyframes dropped".into()],
                    ours_dir: "/o/ours/gaussian_blur".into(),
                    reference_dir: "/plan/premiere/fidelity/gaussian_blur".into(),
                    frames: 72,
                    samples: 144_000,
                    tolerance: Tolerance::VIDEO,
                },
            ],
            reference_root: "/plan/premiere/fidelity".into(),
        };
        let md = premiere_md(&m);
        assert!(md.contains("640×360, 24 fps, 48000 Hz"), "{md}");
        assert!(md.contains("### Baseline") && md.contains("### Effects"));
        assert!(md.contains("- XML complete: import, export, done."));
        assert!(md.contains("  1. Apply it\n  1. Blurriness 20\n"));
        assert!(md.contains("- By script: **Gaussian Blur (Legacy)**: Blurriness = 20.0, Repeat Edge Pixels = false\n"), "{md}");
        assert!(md.contains("## By script") && md.contains("premiere/render.py"));
        assert!(md.contains("`/plan/premiere/fidelity/cut/cut.png`"));
        assert!(md.contains("`/plan/premiere/fidelity/gaussian_blur/gaussian_blur.wav`"));
        assert!(md.contains("Exporter notes: point keyframes dropped"));
        let json = serde_json::to_string(&m).unwrap();
        let back: Manifest = serde_json::from_str(&json).unwrap();
        assert_eq!(back, m);
    }
}

//! The Markdown report (`fidelity-report.md`) and the one-line summary a run prints.

use crate::corpus::Compare;
use crate::{CaseResult, Outcome, Verdict};

fn db(v: Option<f64>) -> String {
    match v {
        None => "∞".into(),
        Some(x) if x.is_finite() => format!("{x:.2}"),
        Some(_) => "–".into(),
    }
}

fn pct(n: usize, of: usize) -> f64 {
    if of == 0 { 0.0 } else { n as f64 * 100.0 / of as f64 }
}

fn row(r: &CaseResult) -> String {
    let side = match r.compare {
        Compare::Video => "picture",
        Compare::Audio => "sound",
    };
    let (compared, psnr, de_mean, de_p95, max_abs, snr, lag) = match (&r.video, &r.audio) {
        (Some(v), _) => (
            format!("{} / {} frames", v.frames_compared, v.frames_reference),
            db(v.psnr_db),
            format!("{:.3}", v.de2000_mean),
            format!("{:.2}", v.de2000_p95),
            v.max_abs.to_string(),
            "–".into(),
            "–".into(),
        ),
        (None, Some(a)) => (
            format!("{} / {} samples", a.frames_compared, a.frames_reference),
            "–".into(),
            "–".into(),
            "–".into(),
            format!("{:.5}", a.max_abs),
            db(a.snr_db),
            a.lag.to_string(),
        ),
        (None, None) => ("–".into(), "–".into(), "–".into(), "–".into(), "–".into(), "–".into(), "–".into()),
    };
    let result = match &r.verdict {
        Verdict::Pass if r.known_failure.is_some() => "**pass** (marked known)".to_string(),
        Verdict::Pass => "**pass**".to_string(),
        Verdict::Fail(_) => "**fail**".to_string(),
        Verdict::Known(_) => "**known**".to_string(),
        Verdict::NoReference => "no reference".to_string(),
    };
    let xml = if r.xml_complete { "XML" } else { "manual" };
    format!(
        "| `{}` | {} | {} | {side} | {xml} | {compared} | {psnr} | {de_mean} | {de_p95} | {max_abs} | {snr} | {lag} | {result} |\n",
        r.id,
        r.group,
        if r.effect.is_empty() { "–" } else { &r.effect },
    )
}

/// The report.
pub fn markdown(o: &Outcome) -> String {
    let n = o.results.len();
    let compared = o.compared();
    let known = o.known();
    let expected = compared.saturating_sub(known);
    let passed = o.passed();
    let mut s = String::from("# Fidelity report: FilmCraft against Premiere Pro\n\n");
    s.push_str(&format!(
        "Generated by `cargo xtask fidelity` into `{}`. {n} cases; {compared} with a Premiere render under `{}`; \
         **{passed} / {expected} pass** ({:.1}%), {known} marked as known failures. Picture scores are over 8-bit sRGB frames flattened over black: PSNR \
         over R, G, B (∞ = identical), CIEDE2000 colour difference per pixel (mean and 95th percentile), and the largest \
         channel difference. Sound scores are sample by sample after alignment: SNR of the reference over the difference \
         (∞ = identical), the lag found (reference minus ours, in samples) and the largest sample error. *XML* cases are \
         fully carried by FCP7 XML; *manual* ones needed steps in Premiere (see `PREMIERE.md`). The baseline `cut` case \
         shows the floor set by codec and colour-pipeline differences alone; read the other picture cases against it.\n\n",
        o.out_dir.display(),
        o.reference_dir.as_ref().map(|p| p.display().to_string()).unwrap_or_else(|| "(none)".into()),
        pct(passed, expected),
    ));
    s.push_str("| Case | Group | Feature | Side | Via | Compared | PSNR dB | ΔE₀₀ mean | ΔE₀₀ p95 | Max diff | SNR dB | Lag | Result |\n");
    s.push_str("|---|---|---|---|---|---|---|---|---|---|---|---|---|\n");
    for r in &o.results {
        s.push_str(&row(r));
    }
    let failing: Vec<&CaseResult> = o.results.iter().filter(|r| matches!(r.verdict, Verdict::Fail(_))).collect();
    s.push_str(&format!("\n## Failing ({})\n\n", failing.len()));
    for r in failing {
        if let Verdict::Fail(why) = &r.verdict {
            s.push_str(&format!("- [ ] `{}` ({}): {}\n", r.id, r.title, why.join("; ")));
            if let Some(v) = &r.video
                && let Some((i, p)) = v.worst_frame
            {
                s.push_str(&format!("  - worst frame {i}: PSNR {p:.2} dB; frames in `{}`\n", r.ours_dir.display()));
            }
        }
    }
    let known_results: Vec<&CaseResult> = o.results.iter().filter(|r| matches!(r.verdict, Verdict::Known(_))).collect();
    s.push_str(&format!("\n## Known failures ({})\n\n", known_results.len()));
    if !known_results.is_empty() {
        s.push_str("Expected to fail for the reason given (`CaseDef::known_failure`); not in the pass rate. Fix, then take the mark off.\n\n");
    }
    for r in known_results {
        if let Verdict::Known(why) = &r.verdict {
            s.push_str(&format!("- `{}` ({}): {}\n  - why: {}\n", r.id, r.title, why.join("; "), r.known_failure.as_deref().unwrap_or("")));
        }
    }
    let fixed: Vec<&CaseResult> = o.results.iter().filter(|r| r.verdict == Verdict::Pass && r.known_failure.is_some()).collect();
    if !fixed.is_empty() {
        s.push_str(&format!("\n## Passing though marked known ({})\n\n", fixed.len()));
        for r in fixed {
            s.push_str(&format!("- `{}`: remove its `known_failure` in `crates/fidelity/src/corpus.rs`\n", r.id));
        }
    }
    let missing: Vec<&CaseResult> = o.results.iter().filter(|r| matches!(r.verdict, Verdict::NoReference)).collect();
    s.push_str(&format!("\n## Without a Premiere render ({})\n\n", missing.len()));
    for r in &missing {
        let want = match r.compare {
            Compare::Video => format!("{}.png (numbered stills)", r.id),
            Compare::Audio => format!("{}.wav", r.id),
        };
        s.push_str(&format!("- `{}`: export `{want}` into `{}`\n", r.id, r.reference_dir.display()));
    }
    s.push_str("\n## Tolerances\n\n");
    s.push_str(
        "Provisional until calibrated on the first real renders (then tighten them in `crates/fidelity/src/corpus.rs`, `Tolerance`):\n\n\
         | Kind | PSNR ≥ | ΔE₀₀ mean ≤ | ΔE₀₀ p95 ≤ | SNR ≥ | |lag| ≤ |\n|---|---|---|---|---|---|\n",
    );
    let mut seen: Vec<String> = Vec::new();
    for r in &o.results {
        let t = r.tolerance;
        let key = format!("{t:?}");
        if seen.contains(&key) {
            continue;
        }
        seen.push(key);
        let f = |v: Option<f64>| v.map(|x| format!("{x}")).unwrap_or_else(|| "–".into());
        let kind = match r.compare {
            Compare::Video if r.group == "Baseline" => "baseline picture",
            Compare::Video => "picture",
            Compare::Audio => "sound",
        };
        s.push_str(&format!(
            "| {kind} | {} | {} | {} | {} | {} |\n",
            f(t.min_psnr_db),
            f(t.max_de2000_mean),
            f(t.max_de2000_p95),
            f(t.min_snr_db),
            t.max_lag_samples.map(|v| v.to_string()).unwrap_or_else(|| "–".into())
        ));
    }
    s.push_str("\n## Exporter notes\n\n");
    let mut any = false;
    for r in &o.results {
        for w in &r.warnings {
            any = true;
            s.push_str(&format!("- `{}`: {w}\n", r.id));
        }
    }
    if !any {
        s.push_str("- none: every case exported to FCP7 XML and OTIO without a warning\n");
    }
    s
}

/// One line for the terminal.
pub fn summary(o: &Outcome) -> String {
    let compared = o.compared();
    let known = o.known();
    let expected = compared.saturating_sub(known);
    let passed = o.passed();
    let fixed = o.fixed();
    let missing = o.results.len().saturating_sub(compared);
    let known_s = match (known, fixed) {
        (0, _) => String::new(),
        (1, 0) => "1 known failure, ".into(),
        (1, f) => format!("1 known failure ({f} passing now), "),
        (k, 0) => format!("{k} known failures, "),
        (k, f) => format!("{k} known failures ({f} passing now), "),
    };
    format!(
        "fidelity: {passed}/{expected} cases pass ({:.1}%), {known_s}{missing} without a Premiere render, {} cases in the corpus",
        pct(passed, expected),
        o.results.len()
    )
}

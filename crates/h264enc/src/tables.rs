    /// Every VLC table must be prefix-free (a cheap consistency check on transcription).
    #[test]
    fn vlc_tables_prefix_free() {
        fn check(codes: &[(u8, u32)]) {
            for (i, &(la, ca)) in codes.iter().enumerate() {
                for (j, &(lb, cb)) in codes.iter().enumerate() {
                    if i == j || la == 0 || lb == 0 || la > lb {
                        continue;
                    }
                    assert!(cb >> (lb - la) != ca, "prefix clash {la}:{ca:b} vs {lb}:{cb:b}");
                }
            }
        }
        for t in 0..3 {
            let mut v = vec![];
            for tc in 0..17 {
                for t1 in 0..4 {
                    if t1 <= tc && COEFF_TOKEN_LEN[t][tc][t1] > 0 {
                        v.push((COEFF_TOKEN_LEN[t][tc][t1], COEFF_TOKEN_CODE[t][tc][t1] as u32));
                    }
                }
            }
            assert_eq!(v.len(), 62);
            check(&v);
        }
        let mut v = vec![];
        for tc in 0..5 {
            for t1 in 0..4 {
                if t1 <= tc && COEFF_TOKEN_CDC_LEN[tc][t1] > 0 {
                    v.push((COEFF_TOKEN_CDC_LEN[tc][t1], COEFF_TOKEN_CDC_CODE[tc][t1] as u32));
                }
            }
        }
        assert_eq!(v.len(), 14);
        check(&v);
        for (tc, row) in TOTAL_ZEROS.iter().enumerate() {
            let v: Vec<_> = row.iter().take(16 - tc).map(|&(l, c)| (l, c as u32)).collect();
            check(&v);
        }
        for (i, row) in RUN_BEFORE.iter().enumerate() {
            let n = if i < 6 { i + 2 } else { 15 };
            let v: Vec<_> = row.iter().take(n).map(|&(l, c)| (l, c as u32)).collect();
            check(&v);
        }
    }

    #[test]
    fn chroma_qp_prime_matches_table_8_15() {
        // 8 bits: QPC straight from Table 8-15 (qPI clipped to 0..=51)
        let t: Vec<u8> = (0..52).map(|q| chroma_qp_prime(q, 0, 0)).collect();
        assert_eq!(&t[..30], &(0..30).collect::<Vec<u8>>()[..]);
        assert_eq!(&t[30..], &[29, 30, 31, 32, 32, 33, 34, 34, 35, 35, 36, 36, 37, 37, 37, 38, 38, 38, 39, 39, 39, 39]);
        assert_eq!(chroma_qp_prime(40, 12, 0), 39);
        assert_eq!(chroma_qp_prime(5, -12, 0), 0);
        // 10 bits: QP'Y 0 is QPY -12, qPI -12 maps to itself, QP'C 0; QP'Y 63 is QPY 51 -> QPC 39 -> QP'C 51
        assert_eq!(chroma_qp_prime(0, 0, 12), 0);
        assert_eq!(chroma_qp_prime(12 + 29, 0, 12), 12 + 29);
        assert_eq!(chroma_qp_prime(12 + 30, 0, 12), 12 + 29);
        assert_eq!(chroma_qp_prime(63, 0, 12), 51);
        // the offset can't push qPI below -QpBdOffsetC
        assert_eq!(chroma_qp_prime(0, -12, 12), 0);
    }

/// A property label: 06 0E 2B 34 followed by `rest`, zero padded.
const fn ul(rest: &[u8]) -> [u8; 16] {
    let mut k = [0u8; 16];
    k[0] = 0x06;
    k[1] = 0x0E;
    k[2] = 0x2B;
    k[3] = 0x34;
    let mut i = 0;
    while i < rest.len() && i < 12 {
        k[4 + i] = rest[i];
        i += 1;
    }
    k
}

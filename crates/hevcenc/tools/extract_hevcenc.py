#!/usr/bin/env python3
"""Extract the HEVC tables the software encoder needs from the public spec text.

Usage (spec stays outside the repo; only these constants are committed):
    pdftotext -layout h265.pdf h265.txt
    python3 extract_hevcenc.py h265.txt > <filmcraft>/crates/hevcenc/src/tables.rs

Only the specification text (Rec. ITU-T H.265 v8, 08/2021) is read. Fully parsed
from the text: CABAC initValue tables (9-5..9-35, arranged per initType following
Table 9-4, SCC-only syntax elements skipped), intraPredAngle / invAngle (8-5, 8-6),
QpC (8-10), beta'/tC' (8-12), luma / chroma interpolation taps and the 32x32 DCT
matrix. Level limits (Tables A.8, A.9, A.10) are transcribed from the same text and
shape-checked against it (row counts plus substring spot checks).
"""
import re
import sys

text = open(sys.argv[1], encoding="utf-8").read().replace("\u2212", "-").replace("\u2013", "-")
lines = text.split("\n")


def section_after(title_regex):
    """Lines after the last occurrence of a table title, until the next table title."""
    hits = [i for i, l in enumerate(lines) if re.search(title_regex, l)]
    assert hits, title_regex
    out = []
    for l in lines[hits[-1] + 1:]:
        if re.search(r"^\s*Table \d+-\d+ - ", l):
            break
        out.append(l)
    return out


def init_values(table):
    """All initValue numbers of one initValue table, in ctxIdx order."""
    vals = []
    for l in section_after(r"Table %s - Values of initValue" % re.escape(table)):
        m = re.match(r"^\s*initValue\s+(.*)$", l)
        if m:
            vals += [int(v) for v in m.group(1).split()]
    assert vals, table
    return vals


R = lambda a, b: list(range(a, b + 1))
# (name, initValue table, ctxIdx used per initType 0/1/2; None = absent there.
# Order follows Table 9-4; SCC-only elements (palette, cross-compensation,
# tu_residual_act) instantiate no contexts.)
CABAC = [
    ("SAO_MERGE", "9-5", [[0], [1], [2]]),
    ("SAO_TYPE", "9-6", [[0], [1], [2]]),
    ("SPLIT_CU", "9-7", [R(0, 2), R(3, 5), R(6, 8)]),
    ("CU_TRANSQUANT_BYPASS", "9-8", [[0], [1], [2]]),
    ("CU_SKIP", "9-9", [None, R(0, 2), R(3, 5)]),
    ("PRED_MODE", "9-10", [None, [0], [1]]),
    ("PART_MODE", "9-11", [[0], R(1, 4), R(5, 8)]),
    ("PREV_INTRA_LUMA", "9-12", [[0], [1], [2]]),
    ("INTRA_CHROMA", "9-13", [[0], [1], [2]]),
    ("RQT_ROOT_CBF", "9-14", [None, [0], [1]]),
    ("MERGE_FLAG", "9-15", [None, [0], [1]]),
    ("MERGE_IDX", "9-16", [None, [0], [1]]),
    ("INTER_PRED_IDC", "9-17", [None, R(0, 4), R(5, 9)]),
    ("REF_IDX", "9-18", [None, R(0, 1), R(2, 3)]),
    ("MVP_FLAG", "9-19", [None, [0], [1]]),
    ("SPLIT_TRANSFORM", "9-20", [R(0, 2), R(3, 5), R(6, 8)]),
    ("CBF_LUMA", "9-21", [R(0, 1), R(2, 3), R(4, 5)]),
    ("CBF_CHROMA", "9-22", [R(0, 3) + [12], R(4, 7) + [13], R(8, 11) + [14]]),
    ("ABS_MVD_GT0", "9-23", [None, [0], [2]]),
    ("ABS_MVD_GT1", "9-23", [None, [1], [3]]),
    ("CU_QP_DELTA_ABS", "9-24", [R(0, 1), R(2, 3), R(4, 5)]),
    ("TRANSFORM_SKIP", "9-25", [[0, 3], [1, 4], [2, 5]]),
    ("LAST_X_PREFIX", "9-26", [R(0, 17), R(18, 35), R(36, 53)]),
    ("LAST_Y_PREFIX", "9-27", [R(0, 17), R(18, 35), R(36, 53)]),
    ("CODED_SUB_BLOCK", "9-28", [R(0, 3), R(4, 7), R(8, 11)]),
    ("SIG_COEFF", "9-29", [R(0, 41) + R(126, 127), R(42, 83) + R(128, 129), R(84, 125) + R(130, 131)]),
    ("GT1", "9-30", [R(0, 23), R(24, 47), R(48, 71)]),
    ("GT2", "9-31", [R(0, 5), R(6, 11), R(12, 17)]),
    ("EXPLICIT_RDPCM", "9-32", [None, [0, 2], [1, 3]]),
    ("EXPLICIT_RDPCM_DIR", "9-33", [None, [0, 2], [1, 3]]),
    ("CU_CHROMA_QP_OFFSET_FLAG", "9-34", [[0], [1], [2]]),
    ("CU_CHROMA_QP_OFFSET_IDX", "9-35", [[0], [1], [2]]),
]

out = []
w = out.append
w("// Generated by crates/hevcenc/tools/extract_hevcenc.py from the text of")
w("// Rec. ITU-T H.265 v8 (08/2021). Do not edit.")
w("")
w("// CABAC context layout: base ctxIdx of each syntax element (Table 9-4 order).")
offset = 0
init = [[], [], []]
for name, table, ranges in CABAC:
    vals = init_values(table)
    need = max(max(r) for r in ranges if r is not None) + 1
    assert len(vals) >= need, (table, len(vals), need)
    n = max(len(r) for r in ranges if r is not None)
    for t in range(3):
        r = ranges[t]
        init[t] += [vals[i] for i in r] + [154] * (n - len(r)) if r is not None else [154] * n
    w("pub const %s: usize = %d;" % (name, offset))
    offset += n
w("pub const NUM_CTX: usize = %d;" % offset)
w("")
w("/// initValue per initType (H.265 9.3.2.2). Encoder uses initType 0 (I) and 1 (P).")
w("pub static CABAC_INIT: [[u8; NUM_CTX]; 3] = [")
for t in range(3):
    w("    [%s]," % ", ".join(str(v) for v in init[t]))
w("];")
w("")

angle = {}
modes = []
for l in section_after(r"Table 8-5 - Specification of intraPredAngle"):
    s = l.strip()
    if s.startswith("predModeIntra"):
        modes = [int(v) for v in s.split()[1:]]
    elif s.startswith("intraPredAngle"):
        for mo, v in zip(modes, s.split()[1:]):
            if v != "-":
                angle[mo] = int(v)
assert sorted(angle) == list(range(2, 35)), sorted(angle)
w("/// Table 8-5: intraPredAngle for predModeIntra 0..34 (0 for planar / DC).")
w("pub static INTRA_PRED_ANGLE: [i8; 35] = [%s];" % ", ".join(str(angle.get(i, 0)) for i in range(35)))
inv = {}
for l in section_after(r"Table 8-6 - Specification of invAngle"):
    s = l.strip()
    if s.startswith("predModeIntra"):
        modes = [int(v) for v in s.split()[1:]]
    elif s.startswith("invAngle"):
        vs = [int(v.replace(" ", "")) for v in re.findall(r"-\d+(?: \d{3})?", s)]
        for mo, v in zip(modes, vs):
            inv[mo] = v
assert sorted(inv) == list(range(11, 26)), inv
w("/// Table 8-6: invAngle for predModeIntra 11..25 (index = mode - 11).")
w("pub static INV_ANGLE: [i16; 15] = [%s];" % ", ".join(str(inv[i]) for i in range(11, 26)))
w("")

for l in section_after(r"Table 8-10 - Specification of QpC as a function of qPi"):
    s = l.strip()
    if s.startswith("qPi"):
        qpi = s.split()
    elif s.startswith("QpC"):
        qpc = s.split()
qpi_n = [int(v) for v in qpi[3:-2]]
qpc_n = [int(v) for v in qpc[3:-4]]
assert qpi_n == list(range(30, 44)) and len(qpc_n) == 14, (qpi_n, qpc_n)
w("/// Table 8-10: QpC for qPi = 30..43 (qPi < 30: QpC = qPi; qPi > 43: QpC = qPi - 6).")
w("pub static QPC_30_43: [u8; 14] = [%s];" % ", ".join(map(str, qpc_n)))
w("")

beta, tc = [], []
for l in section_after(r"Table 8-12 - Derivation of threshold variables"):
    s = l.strip()
    if s.startswith("\u03b2"):
        beta += [int(v) for v in s.split()[1:] if v != "-"]
    elif s.startswith("t C"):
        tc += [int(v) for v in s.split()[2:]]
assert len(beta) == 52 and len(tc) == 54, (len(beta), len(tc))
w("/// Table 8-12: beta' for Q = 0..51.")
w("pub static BETA_TABLE: [u8; 52] = [%s];" % ", ".join(map(str, beta)))
w("/// Table 8-12: tC' for Q = 0..53.")
w("pub static TC_TABLE: [u8; 54] = [%s];" % ", ".join(map(str, tc)))
w("")


def taps(eq_no, var):
    for l in lines:
        if "(%s)" % eq_no in l:
            expr = l.split("=", 1)[1].split(">>")[0]
            coef = {}
            for sign, c, k in re.findall(r"([+-]?)\s*(?:(\d+)\s*\*\s*)?%s0,\s*(-?\d)" % var, expr):
                coef[int(k)] = (-1 if sign == "-" else 1) * (int(c) if c else 1)
            return coef
    raise SystemExit("equation %s not found" % eq_no)


luma = []
for eq in ["8-236", "8-237", "8-238"]:
    c = taps(eq, "c")
    got = [c.get(k, 0) for k in range(-3, 5)]
    assert sum(got) == 64, (eq, got)
    luma.append(got)
w("/// Luma 8-tap interpolation taps fL (8-236..8-238), offsets -3..4 (row 0 = 1/4-pel).")
w("pub static LUMA_FILTER: [[i8; 8]; 4] = [[0, 0, 0, 64, 0, 0, 0, 0], %s];"
  % ", ".join("[%s]" % ", ".join(map(str, t)) for t in luma))
chroma = []
for eq in ["8-255", "8-256", "8-257", "8-258", "8-259", "8-260", "8-261"]:
    c = taps(eq, "aX")
    got = [c.get(k, 0) for k in range(-1, 3)]
    assert sum(got) == 64, (eq, got)
    chroma.append(got)
w("/// Chroma 4-tap interpolation taps fC (8-255..8-261), offsets -1..2.")
w("pub static CHROMA_FILTER: [[i8; 4]; 8] = [[0, 64, 0, 0], %s];"
  % ", ".join("[%s]" % ", ".join(map(str, t)) for t in chroma))
w("")


def matrix_rows(eq):
    hits = [k for k, l in enumerate(lines) if "(%s)" % eq in l]
    assert hits, eq
    rows = []
    for l in lines[hits[-1] + 1:]:
        m = re.match(r"^\s*\{([-\d\s]+)\}\s*$", l)
        if m:
            rows.append([int(v) for v in m.group(1).split()])
        elif rows and l.strip() == "}":
            break
    rows = rows[:32]
    assert len(rows) == 32 and all(len(r) == 16 for r in rows), (eq, len(rows))
    return rows


a, b = matrix_rows("8-319"), matrix_rows("8-321")
w("/// DCT matrix (8-319, 8-321): TRANS_MATRIX[n][m] = transMatrix[m][n].")
w("pub static TRANS_MATRIX: [[i8; 32]; 32] = [")
for n in range(32):
    w("    [%s]," % ", ".join(str(v) for v in a[n] + b[n]))
w("];")
w("")

# Level limits (Tables A.8, A.9, A.10), transcribed from the same text; the spot
# checks below guard the shape against spec-version skew.
levels = [  # (level, idc, max_luma_ps, max_luma_sr, max_br_main, max_br_high, max_cpb_main, max_cpb_high)
    ("1", 30, 36864, 552960, 128, None, 350, None),
    ("2", 60, 122880, 3686400, 1500, None, 1500, None),
    ("2.1", 63, 245760, 7372800, 3000, None, 3000, None),
    ("3", 90, 552960, 16588800, 6000, None, 6000, None),
    ("3.1", 93, 983040, 33177600, 10000, None, 10000, None),
    ("4", 120, 2228224, 66846720, 12000, 30000, 12000, 30000),
    ("4.1", 123, 2228224, 133693440, 20000, 50000, 20000, 50000),
    ("5", 150, 8912896, 267386880, 25000, 100000, 25000, 100000),
    ("5.1", 153, 8912896, 534773760, 40000, 160000, 40000, 160000),
    ("5.2", 156, 8912896, 1069547520, 60000, 240000, 60000, 240000),
    ("6", 180, 35651584, 1069547520, 60000, 240000, 60000, 240000),
    ("6.1", 183, 35651584, 2139095040, 120000, 480000, 120000, 480000),
    ("6.2", 186, 35651584, 4278190080, 240000, 800000, 240000, 800000),
]
assert len(levels) == 13
for lv, _idc, ps, sr, _br, _brh, _cpb, _cpbh in levels:
    row = " ".join(l.replace(" ", "") for l in [lv])  # level token without spaces
    assert any(re.match(r"^\s*" + re.escape(row) + r"(?:\.\d)?\s", l) for l in lines), lv
for spot in ["552 960", "66 846 720", "1 069 547 520", "4 278 190 080", "35 651 584"]:
    assert spot in text, spot
assert re.search(r"(?m)^\s*Main\s+1 000\s+1 100\s+1\.500\s+1\.0\s*$", text), "A.10 Main factors"
w("/// Tables A.8/A.9/A.10 (Main profile): per level (idc, max luma picture size,")
w("/// max luma sample rate, max bit rate and max CPB in Br/CpbVclFactor units, main tier).")
w("/// Bit rates and CPB sizes multiply by BrVclFactor = CpbVclFactor * HbrFactor = 1000 * 1.")
w("pub static LEVELS_MAIN: [(u8, u32, u32, u32, u32); 13] = [")
for _lv, idc, ps, sr, br, _brh, cpb, _cpbh in levels:
    w("    (%d, %d, %d, %d, %d)," % (idc, ps, sr, br, cpb))
w("];")
print("\n".join(out))

const fn transpose(t: [[u8; 11]; NB_EBANDS]) -> [[u8; NB_EBANDS]; 11] {
    let mut out = [[0u8; NB_EBANDS]; 11];
    let mut b = 0;
    while b < NB_EBANDS {
        let mut q = 0;
        while q < 11 {
            out[q][b] = t[b][q];
            q += 1;
        }
        b += 1;
    }
    out
}


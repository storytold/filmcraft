use filmcraft_geom::{Affine, Vec2};
use filmcraft_project::TrackMethod;

use super::StabilizerPath;
use super::mesh::MeshFrame;
use super::trajectory_data::{PointConstraint, SUBSPACE_RANK, TrajectorySet};

const MAX_FINITE_SCALE: f64 = f64::MAX;
const GEOMETRY_EPSILON: f64 = 1.0e-10;

/// Settings used while constructing the clip-wide stabilisation plan.
///
/// The parent effect sanitises UI values as well, but this module is also used by cache and
/// regression-test callers.  `build_plan` therefore sanitises every field again before it is used
/// in geometry or an allocation.
#[derive(Clone, Debug)]
pub(super) struct PlanSettings {
    pub smooth_frames: f64,
    pub no_motion: bool,
    pub preserve_scale: bool,
    pub crop_less: f64,
    pub action_safe: f64,
    pub max_scale: f64,
    pub adaptive: bool,
}
/// Cached frame corrections, source cameras, selected zoom envelope and common crop rectangle.
#[derive(Clone, Debug)]
pub(super) struct StabilizationPlan {
    pub corrections: Vec<Affine>,
    pub cameras: Vec<Affine>,
    pub zooms: Vec<f64>,
    /// Analysis-space crop rectangle: `[left, top, right, bottom]`.
    pub crop_rect: [f64; 4],
    /// Optional content-preserving mesh for each frame. `None` means global-only rendering.
    pub meshes: Vec<Option<MeshFrame>>,
}

#[derive(Clone, Copy)]
struct SanitizedSettings {
    smooth_frames: f64,
    no_motion: bool,
    preserve_scale: bool,
    crop_less: f64,
    action_safe: f64,
    max_scale: f64,
    adaptive: bool,
}

fn sanitize_settings(settings: &PlanSettings) -> SanitizedSettings {
    let smooth_frames = if settings.smooth_frames.is_finite() { settings.smooth_frames.max(0.0) } else { 0.0 };
    let crop_less = if settings.crop_less.is_finite() { settings.crop_less.clamp(0.0, 1.0) } else { 0.0 };
    let action_safe = if settings.action_safe.is_finite() { settings.action_safe.clamp(0.0, 1.0) } else { 0.0 };
    let max_scale = if settings.max_scale.is_finite() { settings.max_scale.max(1.0) } else { 1.0 };
    SanitizedSettings {
        smooth_frames,
        no_motion: settings.no_motion,
        preserve_scale: settings.preserve_scale,
        crop_less,
        action_safe,
        max_scale,
        adaptive: settings.adaptive,
    }
}

fn finite_affine(m: Affine) -> Affine {
    if m.a.is_finite() && m.b.is_finite() && m.c.is_finite() && m.d.is_finite() && m.e.is_finite() && m.f.is_finite() { m } else { Affine::IDENTITY }
}

/// Build all expensive, frame-independent stabilisation data.
///
/// Crop trade-off is deliberately geometric.  Smooth Motion first produces the requested smooth
/// correction, then this function attenuates that correction by one clip-global strength until the
/// intersection of all transformed frame polygons fits the `crop_less` crop budget.  Thus a single
/// bad frame cannot force the whole clip to zoom merely because the temporal Gaussian happened to
/// include it.  No Motion skips that attenuation and retains the fixed correction generated by the
/// smoothing module.
pub(super) fn build_plan(path: &StabilizerPath, settings: &PlanSettings) -> StabilizationPlan {
    let settings = sanitize_settings(settings);
    let n = path.steps.len().saturating_add(1);
    let width = path.w as f64;
    let height = path.h as f64;
    let dimensions_ok = path.w > 0 && path.h > 0 && width.is_finite() && height.is_finite();

    let cameras = if dimensions_ok { super::smoothing::camera_path(path) } else { vec![Affine::IDENTITY; n] };
    let corrections = if dimensions_ok {
        super::smoothing::corrections(path, &cameras, settings.smooth_frames, settings.no_motion, settings.preserve_scale)
    } else {
        vec![Affine::IDENTITY; n]
    };

    let corrections = if dimensions_ok && !settings.no_motion {
        crop_budget_corrections(corrections, width, height, settings.crop_less, settings.preserve_scale)
    } else {
        corrections
    };

    let crop_rect = if dimensions_ok { crop_rect_for(&corrections, width, height) } else { [0.0; 4] };
    let mut cover_scales: Vec<f64> = if dimensions_ok {
        corrections.iter().map(|corr| required_cover_scale(*corr, width, height, settings.action_safe)).collect()
    } else {
        vec![MAX_FINITE_SCALE; n]
    };
    let zooms = if settings.adaptive {
        adaptive_zoom(&cover_scales, settings.max_scale, path.fps)
    } else {
        let required = cover_scales.iter().copied().fold(1.0, f64::max);
        let selected = required.min(settings.max_scale).max(1.0);
        cover_scales.fill(selected);
        cover_scales
    };

    StabilizationPlan { corrections, cameras, zooms, crop_rect, meshes: vec![None; n] }
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(super) enum SubspacePlanError {
    Cancelled,
    Fallback(&'static str),
}

/// Build a subspace-backed plan from smoothed trajectories and solve one spatial mesh per frame.
///
/// The callback receives `(completed_frames, solved_mesh_frames)`. It is called once for every
/// processed frame, so planning progress remains truthful even when a frame has no usable mesh.
pub(super) fn build_subspace_plan(
    path: &StabilizerPath,
    data: &TrajectorySet,
    model: &super::subspace::SubspaceModel,
    settings: &PlanSettings,
    progress: &mut dyn FnMut(usize, usize),
) -> Result<StabilizationPlan, SubspacePlanError> {
    if filmcraft_media::cancel::cancelled() {
        return Err(SubspacePlanError::Cancelled);
    }
    let settings = sanitize_settings(settings);
    let planned = super::subspace::planned_basis(data, model, settings.smooth_frames, settings.no_motion).map_err(|error| match error {
        super::subspace::SubspaceError::Cancelled => SubspacePlanError::Cancelled,
        super::subspace::SubspaceError::InvalidInput => SubspacePlanError::Fallback("invalidInput"),
        super::subspace::SubspaceError::InsufficientTracks => SubspacePlanError::Fallback("insufficientPersistentTracks"),
        super::subspace::SubspaceError::NumericalFailure => SubspacePlanError::Fallback("numericalFailure"),
    })?;
    let n = path.steps.len().saturating_add(1);
    let width = path.w as f64;
    let height = path.h as f64;
    if path.w == 0 || path.h == 0 || !width.is_finite() || !height.is_finite() || data.frames == 0 {
        return Err(SubspacePlanError::Fallback("invalidInput"));
    }
    let cameras = super::smoothing::camera_path(path);
    let fallback = super::smoothing::corrections(path, &cameras, settings.smooth_frames, settings.no_motion, settings.preserve_scale);
    let Some(mut corrections) = provisional_corrections(data, model, &planned, &fallback, settings.preserve_scale, n) else {
        return Err(SubspacePlanError::Cancelled);
    };

    if filmcraft_media::cancel::cancelled() {
        return Err(SubspacePlanError::Cancelled);
    }
    let mut meshes = vec![None; n];
    let mut solved = 0usize;
    for frame in 0..n {
        if filmcraft_media::cancel::cancelled() {
            return Err(SubspacePlanError::Cancelled);
        }
        let Some(correction) = corrections.get(frame).copied() else {
            progress(frame.saturating_add(1).min(n), solved);
            continue;
        };
        if correction.inverse().is_none() {
            progress(frame.saturating_add(1).min(n), solved);
            continue;
        }
        let Some(basis) = planned.get(frame).and_then(|value| *value) else {
            progress(frame.saturating_add(1).min(n), solved);
            continue;
        };
        let active_tracks = model.active_tracks(frame);
        let capacity = active_tracks.len().min(160);
        let mut sources = Vec::with_capacity(capacity);
        let mut targets = Vec::with_capacity(capacity);
        let mut lifetimes = Vec::with_capacity(capacity);
        for &track_id in active_tracks {
            if filmcraft_media::cancel::cancelled() {
                return Err(SubspacePlanError::Cancelled);
            }
            let Some(track_index) = usize::try_from(track_id).ok() else { continue };
            let Some(track) = data.tracks.get(track_index) else { continue };
            if track.rejected {
                continue;
            }
            let Some(offset) = frame.checked_sub(track.start) else { continue };
            let Some(&point) = track.points.get(offset) else { continue };
            let Some(coefficients) = model.coefficient(frame, track_index) else { continue };
            let Some(target) = reconstructed_point(coefficients, &basis) else { continue };
            if !point.iter().all(|value| value.is_finite()) || !target.iter().all(|value| value.is_finite()) {
                continue;
            }
            let lifetime = lifetime_weight(offset, track.points.len());
            if lifetime <= 0.0 {
                continue;
            }
            let source = Vec2::new(point[0] as f64 + 0.5, point[1] as f64 + 0.5);
            let target = Vec2::new(target[0] + 0.5, target[1] + 0.5);
            // The mesh solver rejects the whole frame when a single source lies outside
            // [0, width] x [0, height]; the +0.5 pixel-centre shift can push an edge track
            // there, so drop only that constraint and keep the frame's mesh.
            if !source.x.is_finite()
                || !source.y.is_finite()
                || !target.x.is_finite()
                || !target.y.is_finite()
                || source.x < 0.0
                || source.y < 0.0
                || source.x > width
                || source.y > height
            {
                continue;
            }
            sources.push(source);
            targets.push(target);
            lifetimes.push(lifetime);
        }
        if sources.len() < 3 {
            progress(frame.saturating_add(1).min(n), solved);
            continue;
        }
        remove_global_scale_targets(&sources, &mut targets, settings.preserve_scale);
        let mut constraints = Vec::with_capacity(sources.len().min(4096));
        for ((source, target), weight) in sources.into_iter().zip(targets).zip(lifetimes) {
            if filmcraft_media::cancel::cancelled() {
                return Err(SubspacePlanError::Cancelled);
            }
            if !target.x.is_finite() || !target.y.is_finite() {
                continue;
            }
            constraints.push(PointConstraint { source: [source.x, source.y], target: [target.x, target.y], weight });
            if constraints.len() >= 4096 {
                break;
            }
        }
        let Some(saliency) = data.saliency.get(frame).copied() else {
            progress(frame.saturating_add(1).min(n), solved);
            continue;
        };
        if constraints.len() < 3 {
            progress(frame.saturating_add(1).min(n), solved);
            continue;
        }
        if let Some(mesh) = MeshFrame::solve(path.w, path.h, correction, &constraints, &saliency)
            && let Some(slot) = meshes.get_mut(frame)
        {
            *slot = Some(mesh);
            solved = solved.saturating_add(1);
        }
        progress(frame.saturating_add(1).min(n), solved);
    }
    if solved == 0 {
        return Err(SubspacePlanError::Fallback("noUsableMesh"));
    }

    // Solve local residuals against the full model correction first. Applying the crop budget
    // before the solve makes the mesh restore discarded global motion with lifetime-dependent
    // strength, causing nonrigid jumps as tracks appear and disappear.

    if !settings.no_motion {
        corrections = crop_budget_corrections(corrections, width, height, settings.crop_less, settings.preserve_scale);
    }
    let crop_rect = crop_rect_for(&corrections, width, height);
    let mut cover_scales: Vec<f64> = corrections.iter().map(|corr| required_cover_scale(*corr, width, height, settings.action_safe)).collect();
    for frame in 0..n {
        if filmcraft_media::cancel::cancelled() {
            return Err(SubspacePlanError::Cancelled);
        }
        let Some(mesh) = meshes.get(frame).and_then(Option::as_ref) else { continue };
        let Some((inset_x, inset_y)) = mesh.sampling_inset() else {
            cover_scales[frame] = MAX_FINITE_SCALE;
            continue;
        };
        cover_scales[frame] = required_cover_scale_with_inset(corrections[frame], width, height, settings.action_safe, inset_x, inset_y);
    }
    let zooms = if settings.adaptive {
        adaptive_zoom(&cover_scales, settings.max_scale, path.fps)
    } else {
        let required = cover_scales.iter().copied().fold(1.0, f64::max);
        let selected = required.min(settings.max_scale).max(1.0);
        cover_scales.fill(selected);
        cover_scales
    };
    Ok(StabilizationPlan { corrections, cameras, zooms, crop_rect, meshes })
}

fn provisional_corrections(
    data: &TrajectorySet,
    model: &super::subspace::SubspaceModel,
    planned: &[Option<[f64; SUBSPACE_RANK]>],
    fallback: &[Affine],
    preserve_scale: bool,
    frame_count: usize,
) -> Option<Vec<Affine>> {
    let method = if preserve_scale { TrackMethod::PositionRotation } else { TrackMethod::PositionScaleRotation };
    let mut corrections = Vec::with_capacity(frame_count);
    for frame in 0..frame_count {
        if filmcraft_media::cancel::cancelled() {
            return None;
        }
        let Some(basis) = planned.get(frame).and_then(|value| *value) else {
            corrections.push(fallback.get(frame).copied().unwrap_or(Affine::IDENTITY));
            continue;
        };
        let active_tracks = model.active_tracks(frame);
        let mut source = Vec::with_capacity(active_tracks.len().min(160));
        let mut target = Vec::with_capacity(active_tracks.len().min(160));
        for &track_id in active_tracks {
            if filmcraft_media::cancel::cancelled() {
                return None;
            }
            let Some(track_index) = usize::try_from(track_id).ok() else { continue };
            let Some(track) = data.tracks.get(track_index) else { continue };
            if track.rejected {
                continue;
            }
            let Some(offset) = frame.checked_sub(track.start) else { continue };
            let Some(&point) = track.points.get(offset) else { continue };
            let Some(coefficients) = model.coefficient(frame, track_index) else { continue };
            let Some(projected) = reconstructed_point(coefficients, &basis) else { continue };
            let source_point = Vec2::new(point[0] as f64 + 0.5, point[1] as f64 + 0.5);
            let target_point = Vec2::new(projected[0] + 0.5, projected[1] + 0.5);
            if source_point.x.is_finite() && source_point.y.is_finite() && target_point.x.is_finite() && target_point.y.is_finite() {
                source.push(source_point);
                target.push(target_point);
            }
        }
        let correction = if source.len() >= 2 { crate::track::fit_ls(method, &source, &target) } else { None };
        corrections.push(
            correction
                .filter(|m| [m.a, m.b, m.c, m.d, m.e, m.f].iter().all(|value| value.is_finite()))
                .unwrap_or_else(|| fallback.get(frame).copied().unwrap_or(Affine::IDENTITY)),
        );
    }
    Some(corrections)
}

fn remove_global_scale_targets(source: &[Vec2], target: &mut [Vec2], preserve_scale: bool) {
    if !preserve_scale || source.len() != target.len() || source.len() < 2 {
        return;
    }
    let Some(similarity) = crate::track::fit_ls(TrackMethod::PositionScaleRotation, source, target)
        .filter(|m| [m.a, m.b, m.c, m.d, m.e, m.f].iter().all(|value| value.is_finite()))
    else {
        return;
    };
    let Some(rotation) =
        crate::track::fit_ls(TrackMethod::PositionRotation, source, target).filter(|m| [m.a, m.b, m.c, m.d, m.e, m.f].iter().all(|value| value.is_finite()))
    else {
        return;
    };
    for (source, target) in source.iter().zip(target.iter_mut()) {
        // Keep each local trajectory residual while replacing only the fitted global scale.
        let fitted = similarity.apply(*source);
        let residual = *target - fitted;
        let point = rotation.apply(*source) + residual;
        if point.x.is_finite() && point.y.is_finite() {
            *target = point;
        }
    }
}

fn reconstructed_point(coefficients: &[[f64; SUBSPACE_RANK]; 2], basis: &[f64; SUBSPACE_RANK]) -> Option<[f64; 2]> {
    let x = coefficients[0].iter().zip(basis.iter()).map(|(coefficient, component)| coefficient * component).sum::<f64>();
    let y = coefficients[1].iter().zip(basis.iter()).map(|(coefficient, component)| coefficient * component).sum::<f64>();
    (x.is_finite() && y.is_finite()).then_some([x, y])
}

fn lifetime_weight(offset: usize, length: usize) -> f64 {
    const FADE_FRAMES: usize = 50;
    if length < 2 || offset >= length {
        return 0.0;
    }
    let last = length - 1;
    let ramp = if length <= 2 * FADE_FRAMES {
        // For short tracks the two linear ramps meet at a duration-scaled peak. Keep a
        // two-sample plateau for even lengths so the exact duration/(2T) endpoint is representable.
        let left_peak = last / 2;
        let right_peak = length / 2;
        if offset <= left_peak {
            if left_peak == 0 { 0.0 } else { offset as f64 / left_peak as f64 }
        } else if offset >= right_peak {
            let span = last.saturating_sub(right_peak);
            if span == 0 { 0.0 } else { (last - offset) as f64 / span as f64 }
        } else {
            1.0
        }
    } else {
        (offset.min(last - offset) as f64 / FADE_FRAMES as f64).min(1.0)
    };
    let peak = (length as f64 / (2.0 * FADE_FRAMES as f64)).min(1.0);
    (peak * ramp).clamp(0.0, 1.0)
}

fn crop_budget_corrections(corrections: Vec<Affine>, width: f64, height: f64, crop_less: f64, preserve_scale: bool) -> Vec<Affine> {
    if corrections.is_empty() || crop_less >= 1.0 {
        return corrections;
    }
    let full_cost = crop_cost(&corrections, width, height);
    if !full_cost.is_finite() || full_cost <= crop_less + 1.0e-9 {
        return corrections;
    }

    // Similarity crop cost is usually monotonic with correction strength.  A bounded search gives
    // the largest useful strength in O(N) with a fixed (24) number of clip passes, not a dense
    // time solve.  The final check below deliberately handles unusual large rotations where that
    // monotonicity can fail.
    let mut lo = 0.0;
    let mut hi = 1.0;
    let mut candidate = Vec::with_capacity(corrections.len());
    for _ in 0..24 {
        let mid = (lo + hi) * 0.5;
        candidate.clear();
        candidate.extend(corrections.iter().map(|m| blend_correction(*m, mid, width, height, preserve_scale)));
        let cost = crop_cost(&candidate, width, height);
        if cost.is_finite() && cost <= crop_less {
            lo = mid;
        } else {
            hi = mid;
        }
    }
    candidate.clear();
    candidate.extend(corrections.iter().map(|m| blend_correction(*m, lo, width, height, preserve_scale)));
    if !preserve_scale && crop_cost(&candidate, width, height) > crop_less + 1.0e-6 {
        candidate.clear();
        candidate.extend(corrections.iter().map(|m| blend_correction(*m, 0.0, width, height, false)));
    }
    candidate
}

/// Interpolate a similarity correction in centred position/rotation/log-scale coordinates.
///
/// The tracking path is a similarity path, so this avoids the shear and scale artefacts caused by
/// linearly blending matrix coefficients.  Malformed non-similarity input still receives a bounded
/// coefficient interpolation rather than propagating NaN or infinity into the renderer.
fn blend_correction(m: Affine, amount: f64, width: f64, height: f64, preserve_scale: bool) -> Affine {
    let t = if amount.is_finite() { amount.clamp(0.0, 1.0) } else { 0.0 };
    let m = finite_affine(m);
    let cx = width * 0.5;
    let cy = height * 0.5;
    let to_centre = Affine::translate(-cx, -cy);
    let from_centre = Affine::translate(cx, cy);
    let centred = finite_affine(to_centre.then_apply(&m).then_apply(&from_centre));
    let scale = centred.a.hypot(centred.b);
    if scale.is_finite() && scale > 1.0e-12 && centred.c.is_finite() && centred.d.is_finite() {
        let angle = centred.b.atan2(centred.a);
        let log_scale = scale.ln();
        let tx = centred.e * t;
        let ty = centred.f * t;
        let blended_scale = if preserve_scale { scale } else { (log_scale * t).exp() };
        if angle.is_finite() && log_scale.is_finite() && blended_scale.is_finite() && tx.is_finite() && ty.is_finite() {
            let (sn, cs) = (angle * t).sin_cos();
            let blended = Affine { a: blended_scale * cs, b: blended_scale * sn, c: -blended_scale * sn, d: blended_scale * cs, e: tx, f: ty };
            return finite_affine(from_centre.then_apply(&blended).then_apply(&to_centre));
        }
    }
    finite_affine(Affine {
        a: if preserve_scale { m.a } else { lerp(1.0, m.a, t) },
        b: lerp(0.0, m.b, t),
        c: lerp(0.0, m.c, t),
        d: if preserve_scale { m.d } else { lerp(1.0, m.d, t) },
        e: lerp(0.0, m.e, t),
        f: lerp(0.0, m.f, t),
    })
}

fn lerp(a: f64, b: f64, t: f64) -> f64 {
    let value = a + (b - a) * t;
    if value.is_finite() {
        value
    } else if b.is_sign_negative() {
        -MAX_FINITE_SCALE
    } else {
        MAX_FINITE_SCALE
    }
}

fn crop_cost(corrections: &[Affine], width: f64, height: f64) -> f64 {
    let area = width * height;
    if !area.is_finite() || area <= 0.0 {
        return 1.0;
    }
    let rect = crop_rect_for(corrections, width, height);
    let crop_area = (rect[2] - rect[0]).max(0.0) * (rect[3] - rect[1]).max(0.0);
    if !crop_area.is_finite() {
        return 1.0;
    }
    (1.0 - crop_area / area).clamp(0.0, 1.0)
}

fn target_bounds(width: f64, height: f64, action_safe: f64) -> (f64, f64, f64, f64) {
    let safe = if action_safe.is_finite() { action_safe.clamp(0.0, 1.0) } else { 0.0 };
    let mx = safe * width * 0.5;
    let my = safe * height * 0.5;
    let mut left = 0.5 + mx;
    let mut right = width - 0.5 - mx;
    let mut top = 0.5 + my;
    let mut bottom = height - 0.5 - my;
    if right < left {
        left = width * 0.5;
        right = left;
    }
    if bottom < top {
        top = height * 0.5;
        bottom = top;
    }
    (left, top, right, bottom)
}

/// Return the uncapped scale needed to keep every target sample centre inside source sample-centre
/// bounds.  The inverse affine maps each target corner to `q(t) = q0 + t*(q1-q0)`, where
/// `t = 1/z`; intersecting those linear intervals gives the largest feasible `t` and therefore the
/// smallest zoom.  This handles rotation and translation exactly for an affine map, without a
/// binary-search bound or an arbitrary quality cap.
fn required_cover_scale(correction: Affine, width: f64, height: f64, action_safe: f64) -> f64 {
    required_cover_scale_with_inset(correction, width, height, action_safe, 0.5, 0.5)
}

fn required_cover_scale_with_inset(correction: Affine, width: f64, height: f64, action_safe: f64, inset_x: f64, inset_y: f64) -> f64 {
    if !width.is_finite()
        || !height.is_finite()
        || width <= 0.0
        || height <= 0.0
        || !inset_x.is_finite()
        || !inset_y.is_finite()
        || inset_x < 0.5
        || inset_y < 0.5
        || inset_x > width * 0.5
        || inset_y > height * 0.5
    {
        return MAX_FINITE_SCALE;
    }
    let Some(inverse) = correction.inverse() else {
        return MAX_FINITE_SCALE;
    };
    if !inverse.a.is_finite() || !inverse.b.is_finite() || !inverse.c.is_finite() || !inverse.d.is_finite() || !inverse.e.is_finite() || !inverse.f.is_finite()
    {
        return MAX_FINITE_SCALE;
    }
    let (left, top, right, bottom) = target_bounds(width, height, action_safe);
    let cx = width * 0.5;
    let cy = height * 0.5;
    let source_left = inset_x;
    let source_top = inset_y;
    let source_right = width - inset_x;
    let source_bottom = height - inset_y;
    let targets = [Vec2::new(left, top), Vec2::new(right, top), Vec2::new(right, bottom), Vec2::new(left, bottom)];
    let q0 = inverse.apply(Vec2::new(cx, cy));
    if !q0.x.is_finite() || !q0.y.is_finite() {
        return MAX_FINITE_SCALE;
    }
    let mut t_lo = 0.0;
    let mut t_hi = 1.0;
    for target in targets {
        let q1 = inverse.apply(target);
        if !q1.x.is_finite() || !q1.y.is_finite() {
            return MAX_FINITE_SCALE;
        }
        if !intersect_linear_interval(q0.x, q1.x - q0.x, source_left, source_right, &mut t_lo, &mut t_hi)
            || !intersect_linear_interval(q0.y, q1.y - q0.y, source_top, source_bottom, &mut t_lo, &mut t_hi)
        {
            return MAX_FINITE_SCALE;
        }
    }
    if !t_hi.is_finite() || !t_lo.is_finite() || t_hi <= 0.0 || t_hi + GEOMETRY_EPSILON < t_lo {
        return MAX_FINITE_SCALE;
    }
    let scale = 1.0 / t_hi;
    if scale.is_finite() && scale >= 1.0 {
        scale
    } else if scale.is_finite() && scale > 0.0 {
        1.0
    } else {
        MAX_FINITE_SCALE
    }
}

fn intersect_linear_interval(q0: f64, slope: f64, lower: f64, upper: f64, t_lo: &mut f64, t_hi: &mut f64) -> bool {
    if !q0.is_finite() || !slope.is_finite() || !lower.is_finite() || !upper.is_finite() || lower > upper {
        return false;
    }
    if slope.abs() <= 1.0e-15 {
        return q0 >= lower - GEOMETRY_EPSILON && q0 <= upper + GEOMETRY_EPSILON;
    }
    let ta = (lower - q0) / slope;
    let tb = (upper - q0) / slope;
    if !ta.is_finite() || !tb.is_finite() {
        return false;
    }
    *t_lo = (*t_lo).max(ta.min(tb));
    *t_hi = (*t_hi).min(ta.max(tb));
    *t_hi + GEOMETRY_EPSILON >= *t_lo
}

fn frame_polygon(correction: Affine, width: f64, height: f64) -> Option<Vec<Vec2>> {
    if !width.is_finite() || !height.is_finite() || width <= 0.0 || height <= 0.0 {
        return None;
    }
    let points = [Vec2::new(0.0, 0.0), Vec2::new(width, 0.0), Vec2::new(width, height), Vec2::new(0.0, height)];
    let mapped: Vec<Vec2> = points.iter().map(|p| correction.apply(*p)).collect();
    mapped.iter().all(|p| p.x.is_finite() && p.y.is_finite()).then_some(mapped)
}

fn signed_area(polygon: &[Vec2]) -> f64 {
    if polygon.len() < 3 {
        return 0.0;
    }
    let mut area = 0.0;
    for i in 0..polygon.len() {
        let a = polygon[i];
        let b = polygon[(i + 1) % polygon.len()];
        area += a.x * b.y - a.y * b.x;
    }
    area * 0.5
}

fn cross(a: Vec2, b: Vec2, p: Vec2) -> f64 {
    (b.x - a.x) * (p.y - a.y) - (b.y - a.y) * (p.x - a.x)
}

fn clip_edge(polygon: &[Vec2], a: Vec2, b: Vec2, orientation: f64) -> Vec<Vec2> {
    if polygon.is_empty() {
        return Vec::new();
    }
    let mut output = Vec::with_capacity(polygon.len().saturating_add(1));
    let mut previous = polygon[polygon.len() - 1];
    let mut previous_distance = orientation * cross(a, b, previous);
    let mut previous_inside = previous_distance >= -GEOMETRY_EPSILON;
    for &current in polygon {
        let current_distance = orientation * cross(a, b, current);
        let current_inside = current_distance >= -GEOMETRY_EPSILON;
        if current_inside != previous_inside {
            let denominator = previous_distance - current_distance;
            if denominator.abs() > GEOMETRY_EPSILON && denominator.is_finite() {
                let t = (previous_distance / denominator).clamp(0.0, 1.0);
                let intersection = Vec2::new(previous.x + (current.x - previous.x) * t, previous.y + (current.y - previous.y) * t);
                if intersection.x.is_finite() && intersection.y.is_finite() {
                    output.push(intersection);
                }
            }
        }
        if current_inside {
            output.push(current);
        }
        previous = current;
        previous_distance = current_distance;
        previous_inside = current_inside;
    }
    output
}

fn intersection_polygon(corrections: &[Affine], width: f64, height: f64) -> Option<Vec<Vec2>> {
    let first = corrections.first().copied().and_then(|m| frame_polygon(m, width, height))?;
    let first_area = signed_area(&first);
    if !first_area.is_finite() || first_area.abs() <= GEOMETRY_EPSILON {
        return None;
    }
    let mut intersection = first;
    for &correction in corrections.iter().skip(1) {
        let frame = frame_polygon(correction, width, height)?;
        let area = signed_area(&frame);
        if !area.is_finite() || area.abs() <= GEOMETRY_EPSILON {
            return None;
        }
        let orientation = if area >= 0.0 { 1.0 } else { -1.0 };
        for i in 0..frame.len() {
            let a = frame[i];
            let b = frame[(i + 1) % frame.len()];
            intersection = clip_edge(&intersection, a, b, orientation);
            if intersection.len() < 3 {
                return None;
            }
        }
        // A convex intersection can gain one edge per source polygon. Keep preparation bounded
        // on long rotating paths by replacing a complex polygon with a conservative interior
        // rectangle; subsequent intersections can only shrink it.
        if intersection.len() > 32 {
            let [l, t, r, b] = rectangle_in_polygon(intersection);
            if r <= l || b <= t {
                return None;
            }
            intersection = vec![Vec2::new(l, t), Vec2::new(r, t), Vec2::new(r, b), Vec2::new(l, b)];
        }
    }
    let area = signed_area(&intersection);
    (area.is_finite() && area.abs() > GEOMETRY_EPSILON).then_some(intersection)
}

#[derive(Clone, Copy)]
struct RectangleConstraint {
    a: f64,
    b: f64,
    value: f64,
}

fn crop_rect_for(corrections: &[Affine], width: f64, height: f64) -> [f64; 4] {
    let Some(polygon) = intersection_polygon(corrections, width, height) else { return [0.0; 4] };
    rectangle_in_polygon(polygon)
}

fn rectangle_in_polygon(polygon: Vec<Vec2>) -> [f64; 4] {
    let area = signed_area(&polygon).abs();
    if !area.is_finite() || area <= GEOMETRY_EPSILON {
        return [0.0; 4];
    }
    let mut centre = Vec2::ZERO;
    for (index, p) in polygon.iter().enumerate() {
        centre.x += (p.x - centre.x) / (index + 1) as f64;
        centre.y += (p.y - centre.y) / (index + 1) as f64;
    }
    if !centre.x.is_finite() || !centre.y.is_finite() {
        return [0.0; 4];
    }
    let orientation = if signed_area(&polygon) >= 0.0 { 1.0 } else { -1.0 };
    let mut constraints = Vec::with_capacity(polygon.len());
    for i in 0..polygon.len() {
        let a = polygon[i];
        let b = polygon[(i + 1) % polygon.len()];
        let aa = orientation * (a.y - b.y);
        let bb = orientation * (b.x - a.x);
        let cc = orientation * (b.y * a.x - b.x * a.y);
        let value = aa * centre.x + bb * centre.y + cc;
        if !aa.is_finite() || !bb.is_finite() || !value.is_finite() {
            return [0.0; 4];
        }
        constraints.push(RectangleConstraint { a: aa.abs(), b: bb.abs(), value: value.max(0.0) });
    }
    let mut max_hx = MAX_FINITE_SCALE;
    let mut max_hy = MAX_FINITE_SCALE;
    for constraint in &constraints {
        if constraint.a > GEOMETRY_EPSILON {
            max_hx = max_hx.min(constraint.value / constraint.a);
        }
        if constraint.b > GEOMETRY_EPSILON {
            max_hy = max_hy.min(constraint.value / constraint.b);
        }
    }
    if !max_hx.is_finite() || !max_hy.is_finite() || max_hx < 0.0 || max_hy < 0.0 {
        return [0.0; 4];
    }

    let mut best = (0.0, 0.0);
    let mut best_area = 0.0;
    let mut consider = |hx: f64, hy: f64| {
        if !hx.is_finite() || !hy.is_finite() || hx < 0.0 || hy < 0.0 {
            return;
        }
        if !constraints.iter().all(|c| c.a * hx + c.b * hy <= c.value + 1.0e-8) {
            return;
        }
        let candidate_area = hx * hy;
        if candidate_area.is_finite() && candidate_area > best_area {
            best_area = candidate_area;
            best = (hx, hy);
        }
    };
    consider(max_hx, 0.0);
    consider(0.0, max_hy);
    consider(max_hx * 0.5, max_hy * 0.5);
    for c in &constraints {
        if c.a > GEOMETRY_EPSILON && c.b > GEOMETRY_EPSILON {
            consider(c.value / (2.0 * c.a), c.value / (2.0 * c.b));
        }
    }
    // A polygon's maximum-area centred rectangle is either stationary on one constraint or at
    // an intersection of two constraints.  The intersection usually has only a handful of edges
    // (four transformed frame edges); retain a bounded fallback for pathological, highly
    // fragmented intersections rather than turning a hostile clip into quadratic work.
    if constraints.len() <= 32 {
        for i in 0..constraints.len() {
            for j in (i + 1)..constraints.len() {
                let lhs = constraints[i];
                let rhs = constraints[j];
                let determinant = lhs.a * rhs.b - rhs.a * lhs.b;
                if determinant.abs() <= GEOMETRY_EPSILON {
                    continue;
                }
                let hx = (lhs.value * rhs.b - rhs.value * lhs.b) / determinant;
                let hy = (lhs.a * rhs.value - rhs.a * lhs.value) / determinant;
                consider(hx, hy);
            }
        }
    }
    if best_area <= GEOMETRY_EPSILON {
        return [0.0; 4];
    }
    let left = centre.x - best.0;
    let right = centre.x + best.0;
    let top = centre.y - best.1;
    let bottom = centre.y + best.1;
    if left.is_finite() && top.is_finite() && right.is_finite() && bottom.is_finite() && right > left && bottom > top {
        [left, top, right, bottom]
    } else {
        [0.0; 4]
    }
}

/// O(N) log-domain majorizing envelope, limited to 25% logarithmic zoom per second.
/// Two binomial passes soften its corners; a clip-global lift restores every coverage
/// constraint without reintroducing per-frame kinks. Only the user's cap can underfill.
fn adaptive_zoom(required: &[f64], max_scale: f64, fps: f64) -> Vec<f64> {
    if required.is_empty() {
        return Vec::new();
    }
    let cap = if max_scale.is_finite() { max_scale.max(1.0) } else { 1.0 };
    let slope = 0.25 / if fps.is_finite() && fps > 0.0 { fps } else { 30.0 };
    let mut envelope: Vec<f64> = required.iter().map(|&s| if s.is_nan() { MAX_FINITE_SCALE } else { s.clamp(1.0, MAX_FINITE_SCALE) }.ln()).collect();
    for i in (0..envelope.len().saturating_sub(1)).rev() {
        envelope[i] = envelope[i].max(envelope[i + 1] - slope);
    }
    for i in 1..envelope.len() {
        envelope[i] = envelope[i].max(envelope[i - 1] - slope);
    }
    let peak = envelope.iter().copied().fold(0.0, f64::max);
    let mut filtered = envelope.clone();
    let mut scratch = vec![0.0; envelope.len()];
    for _ in 0..2 {
        for (i, value) in scratch.iter_mut().enumerate() {
            let n = filtered.len() - 1;
            *value = (filtered[i.saturating_sub(2)]
                + 4.0 * filtered[i.saturating_sub(1)]
                + 6.0 * filtered[i]
                + 4.0 * filtered[i.saturating_add(1).min(n)]
                + filtered[i.saturating_add(2).min(n)])
                / 16.0;
        }
        std::mem::swap(&mut filtered, &mut scratch);
    }
    let lift = envelope.iter().zip(&filtered).map(|(needed, value)| needed - value).fold(0.0, f64::max);
    filtered.into_iter().map(|v| ((v + lift).min(peak)).exp().min(cap).max(1.0)).collect()
}


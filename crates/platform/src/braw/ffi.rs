/// `struct SafeArray` (only ever handled behind a pointer).
#[repr(C)]
pub struct SafeArray {
    _private: [u8; 0],
}

/// `struct Variant` on Linux and macOS: a type tag and an 8-byte union (the union's string member
/// is a `CFStringRef` on macOS).
#[cfg(not(windows))]
#[repr(C)]
pub struct Variant {
    pub vt: VariantType,
    pub value: VariantValue,
}

impl Variant {
    /// An empty variant for a call to fill.
    #[cfg(not(windows))]
    pub const fn empty() -> Self {
        Self { vt: blackmagicRawVariantTypeEmpty, value: VariantValue { dbl_val: 0.0 } }
    }
    /// An empty variant for a call to fill.
    #[cfg(windows)]
    pub const fn empty() -> Self {
        Self { vt: blackmagicRawVariantTypeEmpty, reserved: [0; 3], value: VariantValue { record: [0; 2] } }
    }
}

/// `VARIANT` on Windows: a `VARTYPE`, three reserved words and a union two pointers wide.
#[cfg(windows)]
#[repr(C)]
pub struct Variant {
    pub vt: VariantType,
    pub reserved: [u16; 3],
    pub value: VariantValue,
}

#[repr(C)]
#[derive(Clone, Copy)]
pub union VariantValue {
    pub i_val: i16,
    pub ui_val: u16,
    pub int_val: i32,
    pub uint_val: u32,
    pub flt_val: f32,
    pub dbl_val: f64,
    pub bstr_val: BrawString,
    pub parray: *mut SafeArray,
    /// The widest member of Windows' union (`BRECORD`: two pointers).
    #[cfg(windows)]
    pub record: [usize; 2],
}

/// An interface pointer's target: the object starts with its vtable pointer.
#[repr(C)]
pub struct Object<V> {
    pub vtbl: *const V,
}


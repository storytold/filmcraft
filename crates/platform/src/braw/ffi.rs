#![allow(non_upper_case_globals)]

use std::ffi::c_void;
#[cfg(target_os = "linux")]
use std::ffi::c_ulong;

pub type Hresult = i32;
/// `ULONG`: `unsigned long`, 64 bits on Linux and 32 on Windows and macOS (`UInt32`).
#[cfg(target_os = "linux")]
pub type Ulong = c_ulong;
#[cfg(not(target_os = "linux"))]
pub type Ulong = u32;
/// Strings: UTF-8 `const char*` on Linux, owned by the API unless a call says otherwise.
#[cfg(target_os = "linux")]
pub type BrawString = *const std::ffi::c_char;
/// Strings: `BSTR` on Windows; one a call returns belongs to the caller (`SysFreeString`).
#[cfg(windows)]
pub type BrawString = *const u16;
/// Strings: `CFStringRef` (a CoreFoundation string) on macOS; one a call returns belongs to the
/// caller (`CFRelease`).
#[cfg(target_os = "macos")]
pub type BrawString = *const c_void;
/// A vtable entry FilmCraft never calls.
pub type Slot = *const c_void;

pub const S_OK: Hresult = 0;
/// `E_NOINTERFACE`: LinuxCOM.h and Apple's CFPlugInCOM.h define this HRESULT themselves.
#[cfg(not(windows))]
pub const E_NOINTERFACE: Hresult = 0x8000_0004_u32 as i32;
#[cfg(windows)]
pub const E_NOINTERFACE: Hresult = 0x8000_4002_u32 as i32;

/// An interface id: LinuxCOM.h's `REFIID` and Apple's (a `CFUUIDBytes`) are its 16 bytes in written
/// order; on Windows it is a `GUID`, whose first three fields are little-endian integers.
#[cfg(not(windows))]
#[repr(C)]
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Iid(pub [u8; 16]);
#[cfg(windows)]
#[repr(C)]
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Iid {
    pub data1: u32,
    pub data2: u16,
    pub data3: u16,
    pub data4: [u8; 8],
}

impl Iid {
    /// The id written `XXXXXXXX-XXXX-XXXX-XXXX-XXXXXXXXXXXX`, as one number.
    #[cfg(not(windows))]
    pub const fn new(id: u128) -> Self {
        Self(id.to_be_bytes())
    }
    /// The id written `XXXXXXXX-XXXX-XXXX-XXXX-XXXXXXXXXXXX`, as one number.
    #[cfg(windows)]
    pub const fn new(id: u128) -> Self {
        Self { data1: (id >> 96) as u32, data2: (id >> 80) as u16, data3: (id >> 64) as u16, data4: (id as u64).to_be_bytes() }
    }
}

/// How `QueryInterface` takes an id: by value on Linux and macOS (`REFIID` is the struct), by
/// reference on Windows (`REFIID` is `const IID&`).
#[cfg(not(windows))]
pub type IidArg = Iid;
#[cfg(windows)]
pub type IidArg = *const Iid;

pub const IID_IUnknown: Iid = Iid::new(0x00000000_0000_0000_C000_000000000046);
/// SDK 6.0's codec interface. It changed (new slots before `SetCallback`) along with the callback
/// interface, whose id did not: a runtime whose codec has this id calls the callback with the 6.0
/// layout.
pub const IID_IBlackmagicRaw: Iid = Iid::new(0xC25C15E2_D1D0_4743_9EA8_F21F69751AF3);
pub const IID_IBlackmagicRawFactory: Iid = Iid::new(0x78DEEB84_98C9_434A_B7E5_7AACC2988399);
pub const IID_IBlackmagicRawClip: Iid = Iid::new(0xA2910203_787B_4BF2_A374_B1A459E2D351);
pub const IID_IBlackmagicRawConfiguration: Iid = Iid::new(0x267E9866_FB40_4BFB_8BF8_96EA3F7DA36E);
pub const IID_IBlackmagicRawCallback: Iid = Iid::new(0xE9F98FAC_33DB_4A65_BB94_8A82B027AED0);
pub const IID_IBlackmagicRawClipAudio: Iid = Iid::new(0x76D4ACED_E0D6_45BB_B547_56B7435B2A1D);


/// The window, Dock, taskbar and app-switcher icon (`assets/app-icon/`, regenerated by
/// `packaging/icons.sh`). macOS gets the tile inside Apple's transparent margin so it matches the
/// size of other Dock icons; Windows and Linux get the full-bleed tile.
fn app_icon() -> egui::IconData {
    #[cfg(target_os = "macos")]
    let (stable, nightly): (&[u8], &[u8]) =
        (include_bytes!("../../../assets/app-icon/filmcraft-macos-512.png"), include_bytes!("../../../assets/app-icon/filmcraft-nightly-macos-512.png"));
    #[cfg(not(target_os = "macos"))]
    let (stable, nightly): (&[u8], &[u8]) = (
        include_bytes!("../../../assets/app-icon/hicolor/256x256/apps/ai.storyteller.filmcraft.png"),
        include_bytes!("../../../assets/app-icon/filmcraft-nightly.png"),
    );
    let png = if build_flavor::COMPILED == build_flavor::BuildFlavor::NightlyV1 { nightly } else { stable };
    eframe::icon_data::from_png_bytes(png).unwrap_or_default()
}

/// Print `text` (stdout, or stderr for an error). A Windows release build has no console
/// (`windows_subsystem = "windows"`), so there it is also shown in a message box: otherwise `--help`
/// would print nothing and a bad option would quit without a word.
fn tell(text: &str, error: bool) {
    if error {
        eprint!("{text}");
    } else {
        print!("{text}");
    }
    #[cfg(all(target_os = "windows", not(debug_assertions)))]
    {
        let level = if error { rfd::MessageLevel::Error } else { rfd::MessageLevel::Info };
        let _ = rfd::MessageDialog::new().set_level(level).set_title(filmcraft_ui_egui::os_window::name()).set_description(text).show();
    }
}

/// The exact version this build reports: the prepared nightly identity, or the workspace version.
fn version_text() -> &'static str {
    env!("FILMCRAFT_BUILT_VERSION")
}

/// The commit the nightly identity was prepared from, when the build was given one.
fn built_commit() -> Option<&'static str> {
    option_env!("FILMCRAFT_BUILT_COMMIT")
}

fn initialize_nightly_process_identity() -> Result<(), process_identity::IdentityError> {
    let app_id = filmcraft_ui_egui::os_window::id_for(filmcraft_ui_egui::os_window::LaunchIdentity::NightlyV1);
    process_identity::initialize(build_flavor::COMPILED == build_flavor::BuildFlavor::NightlyV1, app_id)
}

/// Whether a refusal may also open a native message box. Standard error always carries the reason;
/// this only adds a box where one renders without the app's event loop. Never on macOS: rfd's alert
/// there needs the AppKit run loop this start has not reached, so a refused nightly launch hung in
/// an invisible modal instead of exiting (GridCraft Mac smoke, 2026-11-26).
fn refusal_dialog(flavor: build_flavor::BuildFlavor, desktop_session: bool, macos: bool) -> bool {
    build_flavor::needs_native_error(flavor, desktop_session) && !macos
}

/// Say why a nightly launch profile was refused: in the log, and on a Windows or X11/Wayland desktop
/// also in a native dialog (a Dock or Start Menu start has no console to read). macOS keeps the log
/// and standard error: a modal before its event loop never appears.
fn report_launch_profile_error(error: &str) {
    eprintln!("{} launch profile: {error}", filmcraft_ui_egui::os_window::name());
    let desktop_session = cfg!(windows)
        || cfg!(target_os = "macos")
        || (cfg!(target_os = "linux") && ["DISPLAY", "WAYLAND_DISPLAY"].into_iter().any(|key| std::env::var_os(key).is_some_and(|v| !v.is_empty())));
    if refusal_dialog(build_flavor::COMPILED, desktop_session, cfg!(target_os = "macos")) {
        if let Err(error) = initialize_nightly_process_identity() {
            eprintln!("filmcraft launch profile: {error}");
            return;
        }
        let _ = rfd::MessageDialog::new()
            .set_title(filmcraft_ui_egui::os_window::name())
            .set_description(error)
            .set_level(rfd::MessageLevel::Error)
            .set_buttons(rfd::MessageButtons::Ok)
            .show();
    }
}

/// Select the immutable launch profile before any startup service or side effect, and give the
/// data directory (and every path derived from it) the profile's root.
///
/// Returns the arguments the rest of the start parses, or `None` when this was a version query.
fn prepare_launch() -> Option<Vec<std::ffi::OsString>> {
    let argv: Vec<std::ffi::OsString> = std::env::args_os().skip(1).collect();
    // Plain `--version`/`-V`, or the Launcher's `--launch-profile nightly-v1 --profile-root <dir>
    // --version`: answered before root validation, process identity, logging or any window.
    if build_flavor::COMPILED == build_flavor::BuildFlavor::NightlyV1 && (build_flavor::version_query(&argv) || launch_profile::version_query(&argv)) {
        use std::io::Write as _;
        let _ = writeln!(std::io::stdout(), "FilmCraft {}", build_flavor::version(build_flavor::COMPILED, version_text()));
        return None;
    }
    // The graphics test child is an internal re-entry of this same program
    // (`--test-graphics-start <mode>` [profile tokens]): its mode and root come from the parent,
    // never from the environment.
    let internal = argv.first().is_some_and(|arg| arg == graphics::probe::CHILD_ARG);
    let early = if internal {
        let tail = argv.get(2..).unwrap_or_default().to_vec();
        launch_profile::parse(tail).unwrap_or_else(|error| {
            report_launch_profile_error(&error);
            std::process::exit(2)
        })
    } else {
        let retry = std::env::var_os("FILMCRAFT_GRAPHICS_RELAUNCHED").is_some();
        launch_profile::parse_startup(argv.clone(), retry).unwrap_or_else(|error| {
            report_launch_profile_error(&error);
            std::process::exit(2)
        })
    };
    let early = build_flavor::require_profile(build_flavor::COMPILED, &early.profile)
        .and_then(|()| initialize_nightly_process_identity().map_err(|error| error.to_string()))
        .and_then(|()| {
            launch_profile::prepare(early, |root| launch_profile::validate_root(root, |key| std::env::var_os(key), std::env::current_exe().ok().as_deref()))
        })
        .unwrap_or_else(|error| {
            report_launch_profile_error(&error);
            std::process::exit(2)
        });
    let identity =
        if early.profile.is_nightly() { filmcraft_ui_egui::os_window::LaunchIdentity::NightlyV1 } else { filmcraft_ui_egui::os_window::LaunchIdentity::Stable };
    // Read the launch's own arguments before `install` takes the profile: `runnable_argv` borrows it.
    let runnable = runnable_argv(internal, argv, &early);
    if let Err(error) = launch_profile::install(early.profile).and_then(|()| filmcraft_ui_egui::os_window::select_identity(identity)) {
        report_launch_profile_error(&error);
        std::process::exit(2);
    }
    // Every data root below comes from `default_data_dir`, which the override now answers first:
    // preferences, workspaces, presets, auto-save, recovery, logs, crash logs, caches and models.
    if let Some(root) = launch_profile::current().root()
        && let Err(error) = filmcraft_engine::autosave::set_data_dir_override(root.to_path_buf())
    {
        report_launch_profile_error(&error);
        std::process::exit(2);
    }
    let _ = filmcraft_ui_egui::os_window::set_display_version(match build_flavor::COMPILED {
        build_flavor::BuildFlavor::Stable => version_text().to_owned(),
        build_flavor::BuildFlavor::NightlyV1 => build_flavor::version(build_flavor::COMPILED, version_text()),
    });
    Some(runnable)
}

/// What `main` parses once the profile is selected. A Launcher start gets the profile's own tail
/// (`--` and the file names): the raw argv still holds `--launch-profile`/`--profile-root`, which
/// `args::parse` refuses as unknown options, so every Nightly GUI start would exit 2. The graphics
/// test child keeps its `--test-graphics-start <mode>` re-entry line, and ignores the tokens after
/// it ([`graphics::probe::child_main`]).
fn runnable_argv(internal: bool, argv: Vec<std::ffi::OsString>, launch: &launch_profile::Launch) -> Vec<std::ffi::OsString> {
    if internal { argv } else { launch.args.clone() }
}

fn main() -> eframe::Result {
    let Some(arguments) = prepare_launch() else { return Ok(()) };
    let nightly = launch_profile::current().is_nightly();
    // Windows: the update helper is a copy of this program started with `--finish-update`. A
    // Nightly is updated by ArtCraft Launcher, never by the stable updater.
    #[cfg(windows)]
    if !nightly && let Some(result) = craft_update::self_update::finish(&filmcraft_ui_egui::UPDATE_APP, &arguments) {
        std::process::exit(i32::from(result.is_err()));
    }
    // Windows: the graphics test start (graphics/probe.rs) is this program started with
    // `--test-graphics-start <mode>`. It creates the device the window would, then exits.
    let args: Vec<std::ffi::OsString> = arguments.clone();
    let test_setup = |mode| {
        let mut options = native_options(false);
        graphics::apply(&mut options, mode, eframe::wgpu::Backends::from_env());
        options.wgpu_options.wgpu_setup
    };
    if let Some(code) = graphics::probe::child_main(&args, test_setup) {
        std::process::exit(code);
    }
    // First, so the panic hook and every start-up record are logged (`logging`).
    let logger = logging::install();
    // lossy, so a value that is not Unicode is reported like any other bad port instead of ignored
    // A Nightly start inherits no stable control server: the Launcher protocol has no per-launch
    // options, and a nightly must never share stable's socket or port.
    let env_port = if nightly { None } else { std::env::var_os("FILMCRAFT_CONTROL_PORT").map(|p| p.to_string_lossy().into_owned()) };
    let launch = match args::parse(env_port, arguments.clone()) {
        Ok(Cli::Run(l)) => l,
        Ok(Cli::Help) => {
            tell(args::USAGE, false);
            return Ok(());
        }
        Ok(Cli::Version) => {
            tell(&format!("filmcraft {}\n", version_text()), false);
            return Ok(());
        }
        Err(e) => {
            tell(&format!("filmcraft: {e}\n\n{}", args::USAGE), true);
            std::process::exit(2);
        }
    };
    if nightly && (launch.control_port.is_some() || launch.control_input_only) {
        eprintln!("filmcraft: a nightly-v1 start does not start the stable control server; drive FilmCraft Nightly through ArtCraft Launcher");
        std::process::exit(2);
    }
    let data_root = launch.data_dir.clone().or_else(default_data_dir);
    let log_dir = data_root.as_ref().map(|d| d.join(logging::LOG_DIR));
    log::info!("{} {} ({} {})", filmcraft_ui_egui::os_window::name(), version_text(), std::env::consts::OS, std::env::consts::ARCH);
    // The log file lives next to the crash logs; opened after the arguments, so `--help`,
    // `--version` and usage errors leave no file behind. Records logged until now go in first.
    let mut log_file = None;
    if let Some(logger) = logger {
        match log_dir.as_deref().map(|d| logger.attach_dir(d)) {
            Some(Ok(path)) => {
                log::info!("log file {}", path.display());
                log_file = Some(path);
            }
            Some(Err(e)) => log::warn!("no log file: {e}"),
            None => {
                logger.stderr_only();
                log::warn!("no log file: no data directory (set FILMCRAFT_DATA_DIR or --data-dir)");
            }
        }
    }
    app_nap::disable();
    // The dev desktop entry is stable-only state under the XDG data dir; a Nightly profile is
    // fenced away from it and the Launcher owns its own entry.
    #[cfg(target_os = "linux")]
    if !nightly {
        dev_icon::ensure_dev_desktop_entry();
    }
    // Panics anywhere go to <data dir>/Logs/crash-<day>.log with a backtrace; the UI pass and
    // frame workers catch them and keep running (see filmcraft_ui_egui::crash).
    filmcraft_ui_egui::crash::install(log_dir);
    // OS hardware video decoders (VideoToolbox on macOS) in front of our own; Settings ▸ Playback ▸
    // Hardware decoding switches them off. Unsupported streams and failures use our decoders.
    register_hardware_decoders();
    // Which graphics backends and adapter the window starts with: `--graphics`, else the saved
    // mode, which moves on after starts that died before their window painted (a driver crash),
    // see graphics.rs.
    let backend_override = eframe::wgpu::Backends::from_env();
    let mut graphics = graphics::GraphicsStart::begin(data_root.as_deref(), backend_override.is_some(), launch.graphics);
    // Windows: test the mode in a child process first when anything changed since the last start
    // that worked, so a driver that hangs moves on to the next mode, or ends in a message saying
    // what each mode did, instead of a FilmCraft that runs with no window (#1061, #2634).
    if let Err(msg) = graphics::probe::choose(&mut graphics, launch.graphics.is_some(), backend_override.is_some(), log_file.as_deref()) {
        log::error!("{msg}");
        filmcraft_ui_egui::crash::record(&msg);
        graphics.abandon();
        let _ = rfd::MessageDialog::new().set_title("FilmCraft").set_description(&msg).set_level(rfd::MessageLevel::Error).show();
        std::process::exit(1);
    }
    // The GPU export renderer creates its own wgpu instance with every backend; after a start
    // fell back, that would load the driver that failed. Exports then composite on the CPU.
    if graphics.mode() == graphics::Mode::Default {
        register_gpu_frame_renderer();
    }
    // Nightly session health: a private record, finished only on a controlled exit, so a start
    // that never reached one (a crash, a kill, a driver hang) is reported next time. No document
    // names, paths or diagnostics are collected. Stable starts (and a failed record) own none.
    let (nightly_session, session_health_warning) =
        match nightly_session::Session::begin_with_health(launch_profile::current().root(), version_text(), built_commit()) {
            Ok(state) => state,
            Err(error) => {
                log::warn!("Nightly session health is unavailable: {error}");
                (None, true)
            }
        };
    let previous_nightly_unclean = nightly_session.as_ref().is_some_and(nightly_session::Session::previous_unclean);
    // Set once a window posted the interruption notice; until then the record must survive.
    let unclean_notice_shown = Arc::new(AtomicBool::new(false));
    let nightly_session: nightly_session::Shared = Arc::new(std::sync::Mutex::new(nightly_session));
    if launch_profile::current().is_nightly() {
        // The app's exit hook is the controlled return on macOS, where every quit ends the process
        // inside AppKit's terminate, after `on_exit` and before `run_native` returns.
        let shared = nightly_session.clone();
        let shown = unclean_notice_shown.clone();
        filmcraft_ui_egui::exit_hook::set(Box::new(move || {
            nightly_session::finish_once(&shared, shown.load(Ordering::Relaxed));
        }));
    }
    let session_notice = launch_profile::current().is_nightly().then(|| SessionNotice {
        previous_unclean: previous_nightly_unclean,
        warning: session_health_warning,
        shown: unclean_notice_shown.clone(),
    });
    // A panic in a FilmCraft started again for it saved the next mode for the next launch.
    let mut next_saved = false;
    let started = loop {
        let mut options = native_options(launch.control_port.is_some());
        // Before eframe creates the wgpu instance (e.g. no OpenGL on Windows, see graphics.rs).
        graphics::apply(&mut options, graphics.mode(), backend_override);
        let app_created = Arc::new(AtomicBool::new(false));
        let creator = app_creator(launch.clone(), graphics.clone(), Arc::clone(&app_created), session_notice.clone());
        let run = std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| eframe::run_native(filmcraft_ui_egui::os_window::name(), options, creator)));
        let app_created = app_created.load(Ordering::Relaxed);
        let result = match run {
            Ok(result) => result,
            // After start-up the app's own guards had their chance: as before, the panic goes on.
            Err(panic) if app_created => std::panic::resume_unwind(panic),
            // wgpu turns its validation errors into panics: one before the app existed is a
            // failed graphics start, e.g. a GPU that claimed the window's surface and could not
            // configure it (NVIDIA 470 on Wayland, #2553). The crash log has the backtrace.
            Err(panic) => {
                let what = format!("the graphics device panicked: {}", panic_text(panic.as_ref()));
                log::warn!("graphics start failed: {what}");
                // Logged; not for the in-app error window of a start that follows.
                let _ = filmcraft_ui_egui::crash::take_last();
                // The next mode is saved either way, so the next launch starts in it instead of
                // the ones that failed (software after the integrated GPU).
                next_saved = graphics.step_down(&what);
                // The event loop does not run again in a process it unwound out of (a second
                // `run_native` returns at once, #2558): FilmCraft starts again in that mode, once.
                if next_saved && std::env::var_os(RELAUNCHED).is_none() {
                    graphics.finish();
                    // The start that follows (this program in the next mode) must own the profile:
                    // a parent that keeps the lease makes it a busy secondary with no health
                    // record. Releasing is not a controlled finish, so the record stays for it.
                    nightly_session::release(&nightly_session);
                    match relaunch(graphics.mode()) {
                        Ok(code) => std::process::exit(code),
                        Err(e) => log::error!("can't start FilmCraft again in graphics mode {}: {e}", graphics.mode().name()),
                    }
                }
                Err(eframe::Error::AppCreation(what.into()))
            }
        };
        match &result {
            // wgpu reported the failure (no adapter, device creation failed) before the app
            // existed: try the next mode in this process.
            Err(e) if !app_created && graphics::is_graphics_failure(e) && graphics.step_down(&e.to_string()) => {
                log::warn!("graphics start failed: {e}");
                continue;
            }
            // Closed before the second frame: the window still came up.
            Ok(()) if app_created => graphics.confirm(),
            _ => {}
        }
        break result;
    };
    // However it ended, this start no longer counts as one that died.
    graphics.finish();
    // A controlled return (including a handled startup error): finish the record here, once.
    // On macOS a window that was created already finished it in the exit hook, so this is a no-op.
    nightly_session::finish_once(&nightly_session, unclean_notice_shown.load(Ordering::Relaxed));
    // The window could not be created (no usable GPU / graphics driver, no display): say so
    // instead of exiting silently, and keep the reason in the crash log.
    if let Err(e) = &started {
        // `--control-input-only` without a control server: the session is unreachable by design,
        // and an unattended launch cannot dismiss a dialog. Exit directly with the reason in the
        // log (#3436); every other start failure keeps the window-failure dialog below.
        if let eframe::Error::AppCreation(inner) = e
            && inner.downcast_ref::<control_server::ControlServerRequired>().is_some()
        {
            log::error!("{inner}");
            std::process::exit(1);
        }
        let mut msg = graphics::failure_message(&e.to_string(), graphics.failed(), log_file.as_deref());
        // A panic saved the next mode, and this start could not go on in it: the next one will.
        if next_saved {
            msg.push_str(&format!("\n\nThe next start uses {}.", graphics.mode().label()));
        }
        log::error!("{msg}");
        filmcraft_ui_egui::crash::record(&msg);
        let _ = rfd::MessageDialog::new().set_title("FilmCraft").set_description(&msg).set_level(rfd::MessageLevel::Error).show();
    }
    started
}

/// Set for a FilmCraft started again after its graphics panicked (#2553), so that one does not
/// start a third.
const RELAUNCHED: &str = "FILMCRAFT_GRAPHICS_RELAUNCHED";

/// Start FilmCraft again with the same arguments in graphics `mode` and wait for it; its exit code.
fn relaunch(mode: graphics::Mode) -> std::io::Result<i32> {
    // an AppImage runs from a mount that ends with its first process: start the AppImage itself
    let exe = match std::env::var_os("APPIMAGE") {
        Some(image) => std::path::PathBuf::from(image),
        None => std::env::current_exe()?,
    };
    log::warn!("starting FilmCraft again in graphics mode {}", mode.name());
    let status = std::process::Command::new(exe).args(relaunch_args(std::env::args_os().skip(1), mode)).env(RELAUNCHED, "1").status()?;
    Ok(status.code().unwrap_or(1))
}

/// `args` with any `--graphics <mode>` replaced by `--graphics <mode>` for the new start. The
/// option goes before a `--`, and what follows `--` (files, whatever their names) is kept as it is.
fn relaunch_args(args: impl IntoIterator<Item = std::ffi::OsString>, mode: graphics::Mode) -> Vec<std::ffi::OsString> {
    let mut out = Vec::new();
    let mut args = args.into_iter();
    while let Some(a) = args.next() {
        if a == "--" {
            out.extend(["--graphics".into(), mode.name().into(), a]);
            out.extend(args);
            return out;
        }
        if a == "--graphics" {
            let _ = args.next();
        } else {
            out.push(a);
        }
    }
    out.extend(["--graphics".into(), mode.name().into()]);
    out
}

/// The message of a caught panic, if it has one.
fn panic_text(panic: &(dyn std::any::Any + Send)) -> &str {
    panic.downcast_ref::<String>().map(String::as_str).or_else(|| panic.downcast_ref::<&str>().copied()).unwrap_or("no message")
}

/// The main window's options; built for each start attempt (they hold a one-shot hook).
fn native_options(agent: bool) -> eframe::NativeOptions {
    eframe::NativeOptions {
        viewport: egui::ViewportBuilder::default()
            .with_title(filmcraft_ui_egui::os_window::name())
            .with_inner_size([1600.0, 980.0])
            .with_min_inner_size([900.0, 560.0])
            .with_drag_and_drop(true)
            .with_fullsize_content_view(true)
            .with_titlebar_shown(false)
            .with_title_shown(false)
            // Started for an agent (`--control`): open without taking the user's keyboard focus.
            .with_active(!agent)
            .with_icon(app_icon())
            // Wayland matches the window to `packaging/linux/ai.storyteller.filmcraft.desktop`.
            .with_app_id(filmcraft_ui_egui::os_window::app_id()),
        event_loop_builder: agent_event_loop(agent),
        ..Default::default()
    }
}

/// What a Nightly window must say about the previous session (and that it cannot run the stable
/// updater). `shown` records that a window posted an earlier interruption's notice, so the record
/// is kept until someone has actually seen it.
#[derive(Clone)]
struct SessionNotice {
    previous_unclean: bool,
    warning: bool,
    shown: Arc<AtomicBool>,
}

/// Creates the app once eframe has its window and graphics device; sets `created` when it runs,
/// and confirms the graphics mode once two frames have painted.
fn app_creator(
    launch: Launch,
    graphics: graphics::GraphicsStart,
    created: Arc<AtomicBool>,
    session_notice: Option<SessionNotice>,
) -> eframe::AppCreator<'static> {
    let Launch { control_port, control_input_only, files, demo, startup_flag, recover, data_dir, graphics: _ } = launch;
    Box::new(move |cc| {
        filmcraft_ui_egui::framework::install(&cc.egui_ctx, filmcraft_ui_egui::os_window::app_id())
            .map_err(|error| format!("the UI runtime could not be installed: {error}"))?;
        filmcraft_ui_egui::install_ime_reset_callbacks(&cc.egui_ctx);
        created.store(true, Ordering::Relaxed);
        // Start the control server before anything touches recovery state: `file.recover`
        // consumes its candidate, and an input-only session that must abort (no server) may not
        // take that step first, or the recovered work is lost (#3436).
        let control = control_port.map(|port| control_server::start(port, cc.egui_ctx.clone()));
        if control_input_only && let Some((_, _, Some(why))) = &control {
            return Err(Box::new(control_server::ControlServerRequired(why.reason())));
        }
        // A fallback graphics mode says so in the window, with a button back to the default.
        let notice = graphics.degraded().then(|| {
            let start = graphics.clone();
            filmcraft_ui_egui::graphics_notice::GraphicsNotice::new(graphics.mode().label(), Box::new(move || start.reset_to_default()))
        });
        let confirmed = AtomicBool::new(false);
        cc.egui_ctx.on_end_pass(
            "graphics-start",
            Arc::new(move |ui| {
                if ui.ctx().cumulative_frame_nr() >= 2 && !confirmed.swap(true, Ordering::Relaxed) {
                    graphics.confirm();
                }
            }),
        );
        let mut session = Session::default();
        if let Some(dir) = data_dir.clone().or_else(default_data_dir) {
            let mut cfg = AutosaveConfig::new(dir);
            cfg.local_offset = local_offset;
            if let Err(e) = session.start_autosave(cfg) {
                log::warn!("auto-save and crash recovery unavailable: {e}");
            }
        }
        // voice-over recording reads the microphone through cpal
        session.voiceover.input = Some(Box::new(audio_in::CpalIn::new(&session.prefs.audio_hardware.device_class)));
        let (project, media) = args::project_and_media(&files);
        if let Some(p) = project {
            if let Err(e) = session.execute("file.open", json!({"path": p})) {
                log::error!("{e}");
            }
        } else if !startup_flag && session.prefs.general.at_startup == "openMostRecent" {
            // Settings ▸ General ▸ At Startup ▸ Open Most Recent
            let recent = session.prefs.general.recent_projects.iter().find(|p| std::path::Path::new(p).exists()).cloned();
            match recent {
                Some(p) => {
                    if let Err(e) = session.execute("file.open", json!({"path": p})) {
                        log::error!("{e}");
                    }
                }
                None => {
                    let _ = session.execute("file.openDemoProject", json!({}));
                }
            }
        } else if !startup_flag && session.prefs.general.at_startup == "emptyProject" {
        } else if demo {
            let _ = session.execute("file.openDemoProject", json!({}));
        }
        if !media.is_empty() {
            let _ = session.execute("file.import", json!({"paths": media}));
        }
        if recover == Some(true) && !session.recovery_candidates().is_empty() {
            let id = session.recovery_candidates()[0].id.clone();
            match session.execute("file.recover", json!({"id": id})) {
                Ok(r) => log::info!("recovered {r}"),
                Err(e) => log::error!("recovery failed: {e}"),
            }
        }
        let mut app = FilmcraftApp::new(session);
        app.set_startup_update_check(session_notice.is_none());
        if let Some(health) = session_notice {
            // Updated by ArtCraft Launcher, never by the stable updater.
            app.disable_updates();
            if health.previous_unclean || health.warning {
                let message = if health.previous_unclean {
                    "The previous FilmCraft Nightly session did not finish normally. You can report a problem from About. No diagnostics have been sent."
                } else {
                    "FilmCraft Nightly could not record session health in its private profile. You can still edit, but abnormal-exit detection is unavailable."
                };
                let mut notice = filmcraft_ui_egui::notices::Notice::new(filmcraft_ui_egui::os_window::name(), vec![message.to_owned()]);
                // Cleared only once a kept pass drew the notice: closing before that keeps the
                // interruption record for the next launch instead of dropping it unseen.
                notice.shown = Some(health.shown.clone());
                app.notice = Some(notice);
            }
        }
        app.graphics_notice = notice;
        if recover == Some(false) {
            app.dialog = None;
        }
        app.integrated_titlebar = cfg!(target_os = "macos");
        if let Some(rs) = cc.wgpu_render_state.clone()
            && std::env::var_os("FILMCRAFT_CPU_COMPOSITE").is_none()
        {
            app.set_wgpu(rs);
        }
        // Keep device selection available even when the default device is unavailable.
        // Settings ▸ Audio Hardware is applied on the first frame (`apply_prefs`).
        app.audio = Some(Box::new(audio::CpalOut::new()));
        // The scrub grain gets its own output on its own thread (#2633): opening a device stream
        // can take ~0.6 s, which must never happen in a playhead-drag frame.
        let document_rate = app.session.active_sequence().map(|q| q.settings.sample_rate);
        app.scrub_out = Some(Box::new(audio::CpalScrubOut::new(&app.session.prefs.audio_hardware, document_rate)));
        app.hooks.pick_files = Some(Box::new(|exts: &[&str]| {
            rfd::FileDialog::new()
                .add_filter(filmcraft_ui_egui::i18n::t("Media"), &file_filters::extensions(exts))
                .pick_files()
                .unwrap_or_default()
                .into_iter()
                .map(|p| p.to_string_lossy().to_string())
                .collect()
        }));
        // Link Media ▸ Locate…, Attach Proxies, Reconnect Full Resolution: one path, not imported.
        app.hooks.pick_file_for_relink = Some(Box::new(|exts: &[&str], _hint| {
            rfd::FileDialog::new()
                .add_filter(filmcraft_ui_egui::i18n::t("Media"), &file_filters::extensions(exts))
                .pick_file()
                .map(|p| p.to_string_lossy().to_string())
        }));
        app.hooks.pick_save = Some(Box::new(|name: &str| {
            rfd::FileDialog::new()
                .add_filter(filmcraft_ui_egui::i18n::t("FilmCraft Project"), &file_filters::extensions(&["fcproj"]))
                .set_file_name(name)
                .save_file()
                .map(|p| p.to_string_lossy().to_string())
        }));
        app.hooks.pick_save_as = Some(Box::new(|filter: &str, exts: &[&str], name: &str| {
            // a full path (Quick Export, Export mode) opens the dialog in its folder
            let path = std::path::Path::new(name);
            let mut dialog = rfd::FileDialog::new()
                .add_filter(filmcraft_ui_egui::i18n::t(filter), &file_filters::extensions(exts))
                .set_file_name(path.file_name().map_or(name.into(), std::ffi::OsStr::to_string_lossy));
            if let Some(dir) = path.parent().filter(|d| d.is_dir()) {
                dialog = dialog.set_directory(dir);
            }
            dialog.save_file().map(|p| p.to_string_lossy().to_string())
        }));
        app.hooks.pick_folder = Some(Box::new(|| rfd::FileDialog::new().pick_folder().map(|p| p.to_string_lossy().to_string())));
        app.hooks.pick_folder_at =
            Some(Box::new(|dir: &str| rfd::FileDialog::new().set_directory(dir).pick_folder().map(|p| p.to_string_lossy().into_owned())));
        // Linux: the XDG portal call blocks until the user chooses, which would stop the frame
        // loop (GNOME offers to force-quit the window after about five seconds, #260). Show the
        // dialog on its own thread instead; the app keeps running and acts on the answer.
        #[cfg(target_os = "linux")]
        {
            app.hooks.run_dialog = Some(Box::new(run_dialog_off_thread));
        }
        app.hooks.open_path = Some(Box::new(open_path));
        // Help menu, About and Discord links (#642): eframe is built without its `links`
        // feature, so `ctx.open_url` does nothing on the desktop. Detached, so a launcher
        // that waits for the browser never freezes the UI.
        app.hooks.open_url = Some(Box::new(|url: &str| open::that_detached(url).map_err(|e| e.to_string())));
        app.hooks.clipboard_media = Some(Box::new(clipboard_media));
        app.hooks.clipboard_text = Some(Box::new(|| arboard::Clipboard::new().ok()?.get_text().ok()));
        // Settings ▸ General ▸ Interface Language ▸ System Language (#218).
        app.hooks.cursor_screen_position = Some(Box::new(filmcraft_platform::cursor::cursor_screen_position));
        app.hooks.system_languages = Some(Box::new(|| sys_locale::get_locales().collect()));
        // Settings ▸ Appearance ▸ Appearance Mode ▸ Sync with system on Linux desktops whose
        // compositor reports no theme to winit (no polling: see appearance.rs).
        app.hooks.system_theme = appearance::service();
        app.hooks.raise_without_focus = Some(Box::new(|| {
            window_raise::raise_without_focus();
        }));
        app.hooks.pick_open_file = Some(Box::new(|filter: &str, exts: &[&str]| {
            rfd::FileDialog::new()
                .add_filter(filmcraft_ui_egui::i18n::t(filter), &file_filters::extensions(exts))
                .pick_file()
                .map(|p| p.to_string_lossy().to_string())
        }));
        app.hooks.pick_open_project = Some(Box::new(|| {
            rfd::FileDialog::new()
                .add_filter(filmcraft_ui_egui::i18n::t("FilmCraft Project"), &file_filters::extensions(&["fcproj"]))
                // #1644: where the system MIME database doesn't know `.fcproj`, the project
                // filter hides every saved project; "All files" keeps them reachable.
                .add_filter(filmcraft_ui_egui::i18n::t("All files"), &file_filters::all_files())
                .pick_file()
                .map(|p| p.to_string_lossy().to_string())
        }));
        #[cfg(target_os = "macos")]
        {
            let (rx, update, text_menu) = native_menu::install(&app, cc.egui_ctx.clone());
            app.hooks.pick_color = Some(native_color::picker(text_menu));
            app.command_inbox = Some(rx);
            app.hooks.menu_changed = Some(update);
            app.ui.show_menu_bar = false;
        }
        if let Some((rx, ready, disabled)) = control {
            // A listener that never came up is reported where a user or agent will see it:
            // the status bar and `ui.inspect` → `control` (#3313).
            if let Some(port) = control_port {
                app.control_status = Some(filmcraft_ui_egui::ControlStatus { port, error: disabled.as_ref().map(control_server::DisabledWhy::reason) });
            }
            app = if control_input_only { app.with_control_input_only(rx) } else { app.with_control(rx) };
            // Each cause is shown in the app as a fully translated sentence (the English
            // `reason()` stays for the log and the input-only error).
            match &disabled {
                Some(control_server::DisabledWhy::Token) => {
                    app = app.with_control_notice(filmcraft_ui_egui::ControlNotice::Token);
                }
                Some(control_server::DisabledWhy::Bind { port, error }) => {
                    app = app.with_control_notice(filmcraft_ui_egui::ControlNotice::Bind { port: *port, error: error.clone() });
                }
                None => {}
            }
            // From here the app drains the queue on its first pass: stop rejecting requests.
            ready.store(true, Ordering::Relaxed);
        }
        Ok(Box::new(app))
    })
}

/// Files copied in the file manager, else an image, on the system clipboard (Paste, #611).
fn clipboard_media() -> Option<filmcraft_ui_egui::ClipboardMedia> {
    let mut clipboard = arboard::Clipboard::new().ok()?;
    if let Ok(files) = clipboard.get().file_list()
        && !files.is_empty()
    {
        return Some(filmcraft_ui_egui::ClipboardMedia::Files(files.iter().map(|p| p.to_string_lossy().into_owned()).collect()));
    }
    let image = clipboard.get_image().ok()?;
    Some(filmcraft_ui_egui::ClipboardMedia::Image { width: image.width, height: image.height, rgba: image.bytes.into_owned() })
}

/// Open a file in its default application, or reveal it in the file manager (Edit Original,
/// Reveal Log Files).
fn open_path(path: &str, reveal: bool) -> Result<(), String> {
    let mut cmd = if cfg!(target_os = "macos") {
        let mut c = std::process::Command::new("open");
        if reveal {
            c.arg("-R");
        }
        c.arg(path);
        c
    } else if cfg!(target_os = "windows") {
        let mut c = std::process::Command::new("explorer");
        if reveal {
            c.arg(format!("/select,{path}"));
        } else {
            c.arg(path);
        }
        c
    } else {
        // Linux file managers have no select-file flag: open the parent folder instead.
        let mut c = std::process::Command::new("xdg-open");
        let p = std::path::Path::new(path);
        c.arg(if reveal { p.parent().unwrap_or(p) } else { p });
        c
    };
    cmd.spawn().map(|_| ()).map_err(|e| format!("can't open {path}: {e}"))
}

/// The GPU export frame renderer (filmcraft-gpu's off-screen compositor behind filmcraft-export's
/// frame-renderer hook): exports with GPU rendering Auto composite on the GPU and fall back to the
/// CPU reference renderer wherever it cannot.
struct GpuFrameRenderer(filmcraft_gpu::ExportRenderer);

impl filmcraft_export::FrameRenderer for GpuFrameRenderer {
    fn render(
        &mut self,
        project: &filmcraft_project::Project,
        seq: filmcraft_project::ItemId,
        t: filmcraft_time::Tick,
        opts: filmcraft_render::RenderOptions,
        sources: &dyn filmcraft_render::SourceProvider,
    ) -> Option<filmcraft_render::Image> {
        self.0.render(project, seq, t, opts, sources)
    }

    fn caps(&self) -> filmcraft_render::plan::DeviceCaps {
        self.0.caps()
    }

    fn render_rgba8(
        &mut self,
        project: &filmcraft_project::Project,
        seq: filmcraft_project::ItemId,
        t: filmcraft_time::Tick,
        opts: filmcraft_render::RenderOptions,
        sources: &dyn filmcraft_render::SourceProvider,
    ) -> Option<(usize, usize, Vec<u8>)> {
        self.0.render_rgba8(project, seq, t, opts, sources)
    }
}

fn register_gpu_frame_renderer() {
    filmcraft_export::register_frame_renderer(|| {
        filmcraft_gpu::ExportRenderer::new().map(|r| Box::new(GpuFrameRenderer(r)) as Box<dyn filmcraft_export::FrameRenderer>)
    });
}

